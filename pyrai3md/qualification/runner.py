def _detect_not_converged(proc, input_file, base_dir=None, title=''):
    """Is this non-zero exit the *optimization step budget* stopping early?

    Truncated-step qualification runs may stop the optimization before
    convergence. Such runs must not be reported as failures: the framework
    optimize workflow records the outcome as `failed: Maximum optimization
    steps reached`, and the agent pipeline surfaces it through a non-zero
    exit.

    The evidence has to be the run's own closing status, resolved the way
    `_check_skill_log_status` resolves it (the task's `run_dir` and
    `control.title`, falling back to the input stem). Two false greens came
    from reading the phrase out of whatever text was at hand instead:

    * a composite evaluation whose field probe died closed with `Status:
      error: ... the two probes did not converge to the same reciprocal sum`,
      and the words in that sentence excused four legs (#451's round
      `tmp_20261104_124614`);
    * the same four legs again in round `tmp_20261104_162054`, where the
      yaml carrier's `input_file` is the installed example, so scanning
      beside it found no log at all and fell back to the traceback text.

    A traceback is the failure's own words, not a budget stop, so the scan
    no longer reads one.

    Parameters
    ----------
    proc : subprocess.CompletedProcess
        Finished test subprocess. Kept in the signature so callers do not
        have to know whether the verdict reads it; it is deliberately unused.
    input_file : str
        Test input/config path; locates the log when no anchor is given.
    base_dir : str, optional
        Directory holding the run's artifacts (the task's `run_dir`).
    title : str, optional
        Run title naming the log (`control.title`).

    Returns
    -------
    bool
        True when the run's own closing status is a budget stop.
    """
    del proc  # only the log decides; see the docstring
    if not input_file:
        return False
    config_dir = os.path.dirname(input_file)
    run_dir = base_dir or config_dir or os.getcwd()
    stem = os.path.splitext(os.path.basename(input_file))[0]
    names = ([title] if title else []) + [stem]
    candidates = [os.path.join(run_dir, name + '.log') for name in names]
    if os.path.abspath(config_dir) != os.path.abspath(run_dir):
        candidates.append(os.path.join(config_dir, stem + '.log'))
    log_path = next((path for path in candidates if os.path.exists(path)),
                    None)
    if log_path is None:
        return False
    try:
        with open(log_path, 'r', encoding='utf-8', errors='ignore') as handle:
            lines = handle.read().splitlines()
    except OSError:
        return False
    status_value = closing_status(lines)
    return bool(status_value) and optimization_budget_stop(status_value)


def _stdout_line_buffered():
    """Flush stdout on every line, so the log keeps its real order.

    Redirected to a file, stdout is block-buffered, and the qualification
    run writes nothing to it until the first task verdict -- while the test
    framework's own output goes to stderr and lands immediately. The result
    in the collected log is the banner and header arriving *after* the first
    block of results, which reads as a broken report even though every line
    was printed in the right order.
    """
    try:
        sys.stdout.reconfigure(line_buffering=True)
    except (AttributeError, ValueError):
        # A stream that is not a TextIOWrapper (a captured buffer in a test,
        # or a closed pipe): ordering is already guaranteed there, and a
        # reporting tool must never be the reason a run dies.
        pass


class _OwnedStream:
    """Own file descriptors 1 and 2 for the duration of one task.

    A main test is not confined to this interpreter: the Dispatcher starts
    spawn pool workers, and some tests run `pyrai3md` themselves, and a child
    inherits the descriptors it was launched with. Whatever such a child
    writes -- an INFO line from the framework logger, a bare print -- lands
    in the report at column 0, in the middle of the block that belongs to the
    task printed before it. No switch inside the library can settle that,
    because the writer is a different process; what fixes it is taking the
    descriptor back for the length of the task.

    What was written while the descriptor was owned is kept for the failure
    path (it explains a failure) and dropped for a passing one (a report of a
    pass does not need another process's chatter).
    """

    def __init__(self):
        self._file = tempfile.TemporaryFile(mode='w+b')
        self._saved = None

    def __enter__(self):
        sys.stdout.flush()
        sys.stderr.flush()
        self._saved = (os.dup(1), os.dup(2))
        os.dup2(self._file.fileno(), 1)
        os.dup2(self._file.fileno(), 2)
        return self

    def __exit__(self, *exc_info):
        # Flush every layer that buffered into the swapped descriptor before
        # handing it back, otherwise the tail is written into the report.
        for stream in (sys.stdout, sys.stderr):
            try:
                stream.flush()
            except (AttributeError, OSError, ValueError):
                pass
        os.dup2(self._saved[0], 1)
        os.dup2(self._saved[1], 2)
        os.close(self._saved[0])
        os.close(self._saved[1])
        self._saved = None
        return False

    def take(self):
        """The text written while the descriptor was owned, consumed once."""
        self._file.flush()
        self._file.seek(0)
        text = self._file.read().decode('utf-8', 'replace').strip('\n')
        self._file.close()
        return text


def _print_run_header(results, total):
    """Print the run banner block, flushed so it sits at the top.

    The timestamp printed here is the only one the report carries: a task
    block shows its verdict and its own captured stream, and the chatter of
    anything a task started is owned away (_OwnedStream).
    """
    print('\n' + '=' * 60, flush=True)
    print('  PyRAI3MD Test Run', flush=True)
    print('=' * 60, flush=True)
    print(f'  Timestamp: {results["timestamp"]}', flush=True)
    print(f'  Total tests: {total}', flush=True)
    print('-' * 60, flush=True)


# The sentence a closed switch writes is the same for every task it closed --
# 'disabled by skills.cp2k_skill.test' -- and tmp_20261016_135553 counted 267
# of them against 123 rows that did something. The plan keeps one entry per
# closed task, because a switch that hides nothing cannot be audited; what
# this run *prints* is one row per bucket carrying the same keys with their
# counts, so the log is bounded by the work the round actually did.
CLOSED_SKIP_PREFIX = 'disabled by'


def _run_directory(base_dir, input_file):
    """Where a run's own products land.

    The task's `run_dir` when it carries one (an example runs in its
    qualification directory), else beside the input file (a skill leg),
    else the current directory.

    Parameters
    ----------
    base_dir : str or None
        The task's `run_dir`.
    input_file : str
        The input file the task names.

    Returns
    -------
    str
        The directory the audit reads.
    """
    return base_dir or os.path.dirname(input_file) or os.getcwd()


def _is_closed(entry):
    """Whether a plan task or a result row stands for a closed switch.

    A plan task says it with 'skip', a result row with 'status'; both name
    the key in 'skip_reason', which is the part worth reading.
    """
    if not (entry.get('skip') or entry.get('status') == 'skip'):
        return False
    return str(entry.get('skip_reason') or '').startswith(CLOSED_SKIP_PREFIX)


def _folded_count(tasks):
    """How many rows this bucket will print: its live tasks plus one summary."""
    closed = sum(1 for task in tasks if _is_closed(task))
    return len(tasks) - closed + (1 if closed else 0)


def _closed_summary_row(bucket, closed_rows):
    """Build the one row that stands for a bucket's closed tasks.

    `skip_count` is what the row is worth in every total, and
    `closed_reasons` keeps the count per key so the report can still answer
    "which switch, and how much did it close".
    """
    reasons = {}
    for row in closed_rows:
        reason = row.get('skip_reason') or 'Prerequisites not met'
        reasons[reason] = reasons.get(reason, 0) + 1
    keys = ', '.join('%s x%d' % (reason, count)
                     for reason, count in sorted(reasons.items()))
    return {
        'name': '%s_closed' % bucket,
        'mode': '',
        'status': 'skip',
        'skip_count': len(closed_rows),
        'skip_reason': 'closed by %d switch(es)' % len(reasons),
        'closed_reasons': reasons,
        'details': keys,
    }


def _fold_closed(bucket_rows, closed_rows, bucket, idx, total):
    """Append and print the bucket's summary row, if it has closed tasks.

    Returns the running counter, which moves only when a row is added.
    """
    if not closed_rows:
        return idx
    summary = _closed_summary_row(bucket, closed_rows)
    bucket_rows.append(summary)
    idx += 1
    _print_single_result(summary, idx, total)
    return idx


def _execute_task(task, plan, config):
    """Run one planned task through the route its descriptor names.

    One dispatch for both execution modes: a local round calls this per
    task, and a slurm round's job calls it inside the allocation. The
    verdict logic therefore cannot differ between the two.

    Parameters
    ----------
    task : dict
        Task descriptor from the plan.
    plan : dict
        Full test plan.
    config : dict
        Parsed pmd_env.yaml configuration.

    Returns
    -------
    dict
        Test result.
    """
    # A planned skip is a row, not a run: a closed switch, a postponed
    # example and a host without an engine all report here.
    if task.get('skip'):
        reason = task.get('skip_reason', 'Prerequisites not met')
        return {
            'name': task.get('name', ''),
            'mode': task.get('mode', ''),
            'theory': task.get('theory', ''),
            'status': 'skip',
            'skip_reason': reason,
            'details': reason,
            'input_file': task.get('input_file', ''),
        }
    # The verification and integration files carry a `file` and no launch
    # script; every subprocess-driven task carries a script (and a
    # benchmark one carries its mode).
    if task.get('file') and not task.get('script'):
        # A test that partitions its own work reads the part it owns from
        # the task's environment; the planner is the only writer, and the
        # variable is unset for a direct run of the file.
        overrides = task.get('env') or {}
        previous = {key: os.environ.get(key) for key in overrides}
        os.environ.update({key: str(value)
                           for key, value in overrides.items()})
        try:
            return _run_main_test(task)
        finally:
            for key, value in previous.items():
                if value is None:
                    os.environ.pop(key, None)
                else:
                    os.environ[key] = value
    if task.get('mode') == 'benchmark':
        return _run_benchmark_test(task, plan, config)
    return _run_skill_test(task, plan, config)


def run_tests(plan, config):
    """Execute all tests in the plan and collect results.

    Each test result is printed immediately upon completion.

    Parameters
    ----------
    plan : dict
        Test plan from manager.generate_plan().
    config : dict
        Parsed pmd_env.yaml configuration.

    Returns
    -------
    dict
        Collected test results.
    """
    work_dir = plan.get('work_dir')
    if not work_dir:
        raise ValueError(
            'plan carries no work_dir; build it with '
            'manager.generate_plan() or manager.create_work_dir()')

    results = {
        'main_results': [],
        'example_results': [],
        'skill_results': [],
        'benchmark_results': [],
        'timestamp': time.strftime('%Y-%m-%d %H:%M:%S'),
        'status': 'running',
    }

    main_tests = plan.get('main_tests', [])
    example_tests = plan.get('example_tests', [])
    skill_tests = plan.get('skill_tests', [])
    benchmark_tests = plan.get('benchmark_tests', [])
    # The counter the reader watches is the number of rows this run prints,
    # not the number of entries the plan lists: a bucket whose switches are
    # closed contributes one row holding all of their reasons.
    total = sum(_folded_count(b)
                for b in (main_tests, example_tests, skill_tests,
                          benchmark_tests))
    idx = 0

    # Ordering first: everything this run prints goes out line by line, then
    # the banner block, then the tasks. Console logging is turned off after
    # the header so the header itself still reaches the file.
    _stdout_line_buffered()

    # A slurm round keeps the plan and the report, and changes only where
    # the tasks run: each case group becomes one submitted job.
    if jobs.scheduler_mode(config) == 'slurm':
        return _run_grouped(plan, config, results, total)

    # Print test header
    _print_run_header(results, total)

    # Run main tests (in-process; a slurm round wraps them in one job)
    closed = []
    for task in main_tests:
        result = _execute_task(task, plan, config)
        if _is_closed(result):
            closed.append(result)
            continue
        idx += 1
        results['main_results'].append(result)
        _print_single_result(result, idx, total)
    idx = _fold_closed(results['main_results'], closed, 'main', idx, total)

    # Run example qualification (official workflow YAMLs, two modes:
    # pyrai3md yaml + pyrai3md input; agent mode is not planned for
    # examples, see manager._plan_example_tests)
    closed = []
    for task in example_tests:
        result = _execute_task(task, plan, config)
        if _is_closed(result):
            closed.append(result)
            continue
        idx += 1
        results['example_results'].append(result)
        _print_single_result(result, idx, total)
    idx = _fold_closed(results['example_results'], closed, 'example',
                       idx, total)

    # Run skill tests
    closed = []
    for task in skill_tests:
        result = _execute_task(task, plan, config)
        if _is_closed(result):
            closed.append(result)
            continue
        idx += 1
        results['skill_results'].append(result)
        _print_single_result(result, idx, total)
    idx = _fold_closed(results['skill_results'], closed, 'skill', idx, total)

    # Run benchmark calibration tests (fourth and final phase):
    # application-level algorithm and performance benchmarks; the
    # compute subprocess runs first, then the benchmark task
    # module's evaluate_run analyzes the run directory in-process.
    closed = []
    for task in benchmark_tests:
        result = _execute_task(task, plan, config)
        if _is_closed(result):
            closed.append(result)
            continue
        idx += 1
        results['benchmark_results'].append(result)
        _print_single_result(result, idx, total)
    idx = _fold_closed(results['benchmark_results'], closed, 'benchmark',
                       idx, total)

    # Every row the plan carried is accounted for: the buckets hold what ran
    # plus one folded row each, and the folded rows carry the counts of what
    # the switches closed.
    if idx != total:  # pragma: no cover - guards the counter against itself
        print(f'  counter finished at {idx} of a planned {total}', flush=True)

    # Determine overall status: the overall verdict is binary
    # (pass/fail only); skipped tests never fail the run but are
    # reported as a [SKIP n] suffix at display time.
    all_results = (results['main_results']
                   + results['example_results']
                   + results['skill_results']
                   + results['benchmark_results'])
    failed = (any(r.get('status') == 'error' for r in all_results)
              or any(r.get('status') == 'fail' for r in all_results))
    results['status'] = 'fail' if failed or not all_results else 'pass'

    # Write results file
    _write_results(results, work_dir)

    return results


def _build_sequence(plan, config):
    """The print order of a round, with the rows that need no job.

    A bucket's tasks come in plan order and its closed tasks fold into
    one summary at the bucket's end, exactly as the local loops print
    them. Tasks the switches closed (and planned skips such as a host
    without an engine) are resolved here: they need no allocation, and
    resolving them first keeps the log moving while jobs wait in the
    queue.

    Parameters
    ----------
    plan : dict
        Test plan from manager.generate_plan().
    config : dict
        Parsed pmd_env.yaml configuration.

    Returns
    -------
    list of dict
        Items with `kind` 'task' or 'fold'; a task item carries either
        a resolved `row` or the round-wide `index` its job will write.
    """
    buckets = (
        ('main', 'main_tests', 'main_results'),
        ('example', 'example_tests', 'example_results'),
        ('skill', 'skill_tests', 'skill_results'),
        ('benchmark', 'benchmark_tests', 'benchmark_results'),
    )
    sequence = []
    index = 0
    for label, bucket_key, result_key in buckets:
        closed = []
        for task in plan.get(bucket_key, []) or []:
            if task.get('skip'):
                row = _execute_task(task, plan, config)
                if _is_closed(row):
                    closed.append(row)
                else:
                    sequence.append({
                        'kind': 'task', 'bucket': label,
                        'result_key': result_key, 'row': row,
                    })
            else:
                sequence.append({
                    'kind': 'task', 'bucket': label,
                    'result_key': result_key, 'index': index,
                    'task': task,
                })
            index += 1
        if closed:
            sequence.append({
                'kind': 'fold', 'bucket': label,
                'result_key': result_key, 'rows': closed,
            })
    return sequence


def _write_results_partial(results, work_dir):
    """Persist what has been printed so far, without a status file.

    deploy only treats a round as finished when `status.json` exists,
    so a partial results.json cannot make it stop early; it is what a
    crashed round leaves behind for a person to read.
    """
    payload = dict(results)
    payload['status'] = 'running'
    path = os.path.join(work_dir, 'results.json')
    temporary = path + '.tmp'
    with open(temporary, 'w', encoding='utf-8') as handle:
        json.dump(payload, handle, indent=2, ensure_ascii=False)
    os.replace(temporary, path)


def _run_grouped(plan, config, results, total):
    """Run the plan as independent Slurm jobs, one group each.

    The report is the local report: the same header, the same
    `[idx/total]` rows in plan order, the same folded closed rows and
    the same final status. Jobs run in plan order only in what they
    print: a row is held until every row before it is available.

    Parameters
    ----------
    plan : dict
        Test plan from manager.generate_plan().
    config : dict
        Parsed pmd_env.yaml configuration.
    results : dict
        Result skeleton from run_tests.
    total : int
        The number of rows this round prints.

    Returns
    -------
    dict
        The collected results.
    """
    work_dir = plan['work_dir']
    _print_run_header(results, total)
    sequence = _build_sequence(plan, config)
    pending = {}
    cursor = 0
    idx = 0

    def flush():
        nonlocal cursor, idx
        while cursor < len(sequence):
            item = sequence[cursor]
            if item['kind'] == 'task':
                if 'row' not in item:
                    row = pending.get(item['index'])
                    if row is None:
                        break
                    item['row'] = row
                idx += 1
                results[item['result_key']].append(item['row'])
                _print_single_result(item['row'], idx, total)
            else:
                idx = _fold_closed(results[item['result_key']], item['rows'],
                                   item['bucket'], idx, total)
            cursor += 1
            at_bucket_end = (cursor == len(sequence)
                             or sequence[cursor]['bucket'] != item['bucket'])
            if at_bucket_end:
                _write_results_partial(results, work_dir)

    flush()

    try:
        if shutil.which('sbatch') is None:
            message = ('environment.scheduler is slurm but sbatch is not '
                       'available on this host')
            print('Error: %s' % message, flush=True)
            jobs_dir = os.path.join(work_dir, 'jobs')
            for group in jobs.build_groups(plan):
                for index, row in jobs.collect(work_dir, group, jobs_dir,
                                               message):
                    pending[index] = row
                    flush()
        else:
            def on_row(index, row):
                pending[index] = row
                flush()

            def on_pulse(stats):
                print('  [queue] %s' % stats, flush=True)

            prepared = jobs.execute(plan, config, on_row, on_pulse)
            if prepared.get('interrupted'):
                print('  Round interrupted: remaining jobs were cancelled.',
                      flush=True)
    except Exception as exc:  # noqa: BLE001 - a round must still report
        # A crash in the orchestrator is not a hang: the rows already
        # produced stand, the rest are reported as errors, and a terminal
        # status is written so the deployment poller stops.
        print('Error: grouped execution failed: %s' % exc, flush=True)
        traceback.print_exc()
        for item in sequence[cursor:]:
            if item['kind'] == 'task' and 'row' not in item:
                task = item.get('task', {})
                item['row'] = {
                    'name': task.get('name', ''),
                    'mode': task.get('mode', ''),
                    'theory': task.get('theory', ''),
                    'input_file': task.get('input_file', ''),
                    'status': 'error',
                    'details': 'round aborted: %s' % exc,
                }
        flush()
        results['status'] = 'error'
        _write_results(results, work_dir)
        return results

    flush()
    all_results = (results['main_results']
                   + results['example_results']
                   + results['skill_results']
                   + results['benchmark_results'])
    failed = (any(r.get('status') == 'error' for r in all_results)
              or any(r.get('status') == 'fail' for r in all_results))
    results['status'] = 'fail' if failed or not all_results else 'pass'
    _write_results(results, work_dir)
    return results


def _run_main_test(task):
    """Run a single main test file using unittest.

    Parameters
    ----------
    task : dict
        Test task descriptor with 'name' and 'file' keys.

    Returns
    -------
    dict
        Test result with name, status, and details.
    """
    name = task['name']
    test_file = task['file']

    if task.get('skip', False):
        reason = task.get('skip_reason', 'Prerequisites not met')
        return {
            'name': name,
            'mode': 'local',
            'status': 'skip',
            'skip_reason': reason,
            'details': reason,
        }

    result = {
        'name': name,
        'mode': 'local',
        'status': 'error',
        'details': '',
    }

    try:
        # Two captures, for two different leaks. The StringIO holds the
        # framework's own per-test lines: TextTestRunner writes to stderr by
        # default, which arrives at column 0 in between the blocks printed
        # under the counter. The owned descriptor holds what the test starts:
        # a Dispatcher spawn worker, a `pyrai3md` child, or a bare print --
        # those write to the inherited file descriptor, not to this stream.
        stream = io.StringIO()
        owned = _OwnedStream()
        with owned:
            loader = unittest.TestLoader()
            suite = loader.discover(
                os.path.dirname(test_file),
                pattern=os.path.basename(test_file),
            )
            runner = unittest.TextTestRunner(verbosity=2, stream=stream)
            test_result = runner.run(suite)
        stray = owned.take()

        if test_result.testsRun == 0:
            # A module with no collected case is not a pass. unittest's
            # wasSuccessful() is True for an empty suite, which is how a
            # pytest-style module or a helper file used to certify itself.
            result['status'] = 'error'
            result['details'] = (
                '0 cases collected from %s; unittest discovery found no '
                'test method (a zero-case module is not a pass)'
                % os.path.basename(test_file))
            return result
        skipped = getattr(test_result, 'skipped', [])
        if (not test_result.failures and not test_result.errors
                and skipped and len(skipped) == test_result.testsRun):
            # Every collected case skipped: the module's own guard (a
            # missing optional dependency, for one) declined to run any
            # of it, so a pass here would certify nothing.
            reason = skipped[0][1] or 'all collected tests were skipped'
            result['status'] = 'skip'
            result['skip_reason'] = reason
            result['details'] = reason
            return result
        if test_result.wasSuccessful():
            result['status'] = 'pass'
        elif test_result.failures:
            result['status'] = 'fail'
        elif test_result.errors:
            result['status'] = 'error'

        # Tagged so a passing block still shows what it counted: the print
        # side keeps the tag lines and drops the verbatim case listing.
        summary = ('[UNIT] ran=%d failures=%d errors=%d'
                   % (test_result.testsRun,
                      len(test_result.failures), len(test_result.errors)))

        if result['status'] == 'pass':
            # A pass drops the chatter its children left on the descriptor.
            result['details'] = summary
        else:
            details = stream.getvalue().strip('\n')
            if stray:
                details += '\n' + stray
            result['details'] = details + '\n' + summary

        # Collect error and failure tracebacks
        if test_result.errors:
            result['error_tracebacks'] = [
                {'test': str(test), 'traceback': tb}
                for test, tb in test_result.errors
            ]
        if test_result.failures:
            result['failure_tracebacks'] = [
                {'test': str(test), 'traceback': tb}
                for test, tb in test_result.failures
            ]

    except Exception as e:
        result['status'] = 'error'
        result['details'] = str(e)

    return result


def _run_skill_test(task, plan, config):
    """Run a skill test via subprocess.

    Executes pre-generated scripts from manager:
    - .sh scripts for local execution (bash <script>.sh)
    - .sbatch scripts for slurm submission (sbatch <script>.sbatch)

    A task with neither script is reported as an error: the planner
    writes one for every runnable task.

    Parameters
    ----------
    task : dict
        Skill test task descriptor.
    plan : dict
        Full test plan (contains slurm and export config).
    config : dict
        Parsed pmd_env.yaml configuration.

    Returns
    -------
    dict
        Test result with name, mode, status, and details.
    """
    name = task['name']
    mode = task['mode']
    input_file = task.get('input_file', '')
    use_slurm = task.get('use_slurm', False)
    skill_slurm = task.get('skill_slurm', False)
    script = task.get('script', '')

    result = {
        'name': name,
        'mode': mode,
        'theory': task.get('theory', ''),
        'status': 'error',
        'details': '',
    }

    # Check if task should be skipped due to missing prerequisites
    if task.get('skip', False):
        result['status'] = 'skip'
        result['skip_reason'] = task.get('skip_reason', 'Prerequisites not met')
        result['details'] = result['skip_reason']
        result['input_file'] = input_file
        return result
    if task.get('status') == 'error':
        # The planner already knows this row cannot run (a failed case
        # generation, a skill that is not installed). It is an error row,
        # not a skip: the round must not count it as a pass.
        result['status'] = 'error'
        result['details'] = task.get('details') or task.get('skip_reason', '')
        result['input_file'] = input_file
        return result

    # Build command: prefer pre-generated scripts. Slurm submission
    # always blocks with 'sbatch -W' (same convention as the skill
    # slurm runners); fire-and-forget submission is not allowed.
    if use_slurm and task.get('sbatch_script'):
        command = f'sbatch -W {task["sbatch_script"]}'
    elif script:
        command = f'bash {script}'
    else:
        # Every runnable example/skill task is planned with a script (the
        # manager writes it beside the generated input); a task without one
        # is a planning defect, not a mode this runner can reconstruct.
        result['details'] = (
            'task %s (%s) carries neither a script nor an sbatch script; '
            'the planner writes one for every runnable task' % (name, mode))
        return result

    # Blocking sbatch waits for the job to finish, whose duration is
    # bounded by the slurm time directive; no subprocess timeout on
    # the slurm path. The same applies when the skill submits its own
    # sbatch job (skill_slurm): the local wrapper blocks inside the
    # skill backend. Plain local scripts keep the _timeout guard (from
    # pmd_env.yaml, default 300 s) unless the task carries its own
    # timeout (benchmark tasks ship 3600 s). The generated script
    # embeds `timeout (_timeout - 5)s`, so the engine process group is
    # killed just before this subprocess backstop fires.
    # One reader of `_timeout` (manager._resolve_timeout) so the
    # subprocess backstop and the generated scripts cannot drift.
    from .manager import _resolve_timeout
    default_timeout = _resolve_timeout(config or {})
    timeout = None if (use_slurm or skill_slurm) \
        else int(task.get('timeout', default_timeout))

    # Where this run's own log lives. An example writes it into its run
    # directory under its `control.title` (both differ from the source
    # YAML path), so the task carries the anchor; skill tests leave both
    # unset and keep resolving beside the input file. Both verdict routes
    # read it: the zero-exit status check and the budget-stop excuse for a
    # non-zero exit.
    base_dir = task.get('run_dir') or os.path.dirname(input_file)
    title = task.get('title') or ''
    # The example's declared ensemble/cell live in its source YAML. For
    # the input mode 'input_file' is the generated classic input, so the
    # checks below read the spec through this anchor instead -- otherwise
    # an entire mode runs unjudged and passes silently.
    spec_file = task.get('spec_file') or input_file
    try:
        proc = subprocess.run(
            command,
            shell=True,
            capture_output=True,
            text=True,
            timeout=timeout,
        )

        if proc.returncode == 0:
            result['status'] = 'pass'
            if task.get('mode') == 'skill_runtime':
                # A unit-test task passes with a counted summary, the way the
                # main framework tests do. Its case listing (pytest's dots,
                # unittest's per-case lines) stays in the captured stream for
                # the failure case only.
                result['details'] = '[UNIT] ' + _unit_summary(proc.stdout)
            else:
                result['details'] = _clip_to_lines(proc.stdout, 500, tail=True)
        elif proc.returncode in (124, 137):
            # The execution script's embedded `timeout` killed the
            # engine process group: 124 = timed out (SIGTERM), 137 =
            # SIGKILL escalation. Report a timeout error, not a
            # calculation failure.
            result['status'] = 'error'
            result['details'] = f'Test timed out ({timeout}s)'
        elif _detect_not_converged(proc, input_file, base_dir, title):
            # A truncated-step optimize test may end unconverged;
            # that is an expected outcome (PASS[NOT CONVERGED]),
            # not a crashed calculation.
            result['status'] = 'pass'
            result['details'] = (
                '[NOT CONVERGED] geometry optimization stopped '
                'before convergence within the test step budget'
            )
            # The flag the log-status route sets too (#399), so a consumer can
            # ask the question once instead of parsing either route's prose.
            result['not_converged'] = True
            result['stderr'] = proc.stderr if proc.stderr else ''
        else:
            result['status'] = 'fail'
            # Capture full stderr for traceback, truncate stdout
            result['stderr'] = proc.stderr if proc.stderr else ''
            result['details'] = _clip_to_lines(
                proc.stderr or proc.stdout, 500, tail=True)

    except subprocess.TimeoutExpired:
        result['status'] = 'error'
        result['details'] = f'Test timed out ({timeout}s)'
    except Exception as e:
        result['status'] = 'error'
        result['stderr'] = traceback.format_exc()
        result['details'] = str(e)

    # Post-run artifact checks read the run's own artifacts. They are a
    # separate try: a check that raises says the run's artifacts could not
    # be judged, which is an error, not a pass with the exception text in
    # `details`. Keeping them inside the subprocess try would let the
    # generic handler above leave the earlier PASS in place.
    if result['status'] == 'pass':
        try:
            # Verify the skill's own Status line in its log file: some
            # skill agents write "Status: failed: ..." even when the
            # subprocess exits 0, so the log status takes precedence
            # over the return code.
            _check_skill_log_status(result, input_file, base_dir, title)
            _check_energy_conservation(result, spec_file, config,
                                       base_dir, title,
                                       mode=task.get('mode', ''))
            _check_run_diagnostics(result, spec_file, base_dir, title)
            _check_npt_stability(result, spec_file, config,
                                 base_dir, title)
            _check_minimum_image(result, spec_file, base_dir, title)
            check_cell_optimization(result, spec_file,
                                   base_dir, title)
            _check_adaptive_products(result, spec_file, base_dir, title)
        except Exception:
            result['status'] = 'error'
            result['stderr'] = traceback.format_exc()
            result['details'] = (
                'post-run artifact check failed: %s'
                % traceback.format_exc())

    # Authenticity assertion for skill self-submission: the skill
    # runner silently falls back to run_local for any non-'slurm'
    # execution_mode, so a passing return code alone cannot prove the
    # sbatch path ran. Require the slurm artifacts produced by the
    # skill slurm runner ({project}.sbatch and {project}_slurm.out)
    # somewhere under the test directory.
    if skill_slurm and result['status'] == 'pass':
        # Anchor at the task's own leg directory. The skill directory is
        # shared by every group of a skill, so scanning it would let a
        # parallel group's slurm artifacts certify this one.
        scan_dir = (task.get('run_dir')
                    or os.path.dirname(input_file) or os.getcwd())
        exclude = task.get('sbatch_script')
        sbatch_files, out_files = _find_slurm_artifacts(
            scan_dir, exclude, skill=_slurm_skill_label(task))
        if not sbatch_files or not out_files:
            result['status'] = 'fail'
            result['details'] = (
                f'skill execution_mode=slurm but slurm artifacts are '
                f'missing under {scan_dir} '
                f'(sbatch scripts: {len(sbatch_files)}, '
                f'slurm output files: {len(out_files)}); '
                f'the skill may have silently fallen back to local '
                f'execution'
            )

    return result


def _run_benchmark_test(task, plan, config):
    """Run one benchmark calibration task and evaluate the run.

    The reference + production compute chain runs through the
    generic subprocess path (_run_skill_test); right after it
    finishes the benchmark task module's evaluate_run analyzes the
    task's run directory in-process (metrics, verdict,
    production.pop / reference.pop persistence). Evaluation is a
    qualification tool, never a framework calculation task. The
    tool report lands in result['metrics']; a non-PASS benchmark
    verdict downgrades the result to 'fail' so the overall status
    reflects calibration misses (a failed compute subprocess
    already reports 'fail' and the tool then yields verdict ERROR).

    Parameters
    ----------
    task : dict
        Benchmark task descriptor (carries the task-level timeout,
        the run_dir and the benchmark_task module name planned by
        the benchmark planner).
    plan : dict
        Full test plan.
    config : dict
        Parsed pmd_env.yaml configuration.

    Returns
    -------
    dict
        Test result, extended with 'metrics' from the tool report.
    """
    result = _run_skill_test(task, plan, config)
    if result.get('status') == 'skip':
        return result

    run_dir = task.get('run_dir', '')
    task_module = task.get('benchmark_task', '')
    if not run_dir or not task_module:
        return result

    module = importlib.import_module(
        f'.{task_module}', 'pyrai3md.qualification.benchmark')
    report = module.evaluate_run(run_dir)
    result['metrics'] = report
    verdict = str(report.get('verdict', '')).upper()
    result['benchmark_verdict'] = verdict
    if verdict != 'PASS' and result['status'] == 'pass':
        # Compute chain exited cleanly but the calibration missed
        # its tolerances (FAIL) or could not produce metrics
        # (ERROR). The ERROR verdict carries empty metrics; the
        # report's details.error names the real cause, so print it
        # instead of a bare {}.
        result['status'] = 'fail'
        if report.get('metrics'):
            payload = json.dumps(report['metrics'])[:300]
        else:
            tool_detail = report.get('details', {})
            error_text = tool_detail.get('error', '') \
                if isinstance(tool_detail, dict) else ''
            payload = str(error_text)[:300] or '(no details)'
        result['details'] = f'[BENCHMARK {verdict}] {payload}'
    elif verdict != 'PASS' and result['status'] == 'fail':
        # Keep the compute failure as the primary reason; append
        # the tool diagnostic so the report shows both.
        tool_detail = report.get('details', {})
        if isinstance(tool_detail, dict) and tool_detail.get('error'):
            result['details'] = (
                f'{result.get("details", "")[:300]} '
                f'[benchmark tool: {tool_detail["error"][:150]}]'
            )
    return result


def optimization_budget_stop(status_value: str) -> bool:
    """Is this closing status the *optimization step budget* stopping early?

    The tolerated case is a truncated test optimization -- `failed: Maximum
    optimization steps reached` or `failed: Skill internal optimization did
    not converge` -- and nothing else. Matching the signature anywhere in the
    text (the previous rule) also excused a nested engine failure whose words
    happen to contain one: a multi-center run whose SCF for a centre failed
    closed with `error: Composite evaluation failed (1 term(s)): task
    'qm_task1' (evaluation 2): SCF calculation did not converge` and was
    recorded PASS in round tmp_20261011_184226 with a single frame written.
    So the signature has to be the status itself, minus its `failed:` prefix.
    """
    # The two tolerated texts are optimization-budget stops that a `failed:`
    # status carries by themselves. A nested engine failure reaches this line
    # as an `error:` status -- `error: Composite evaluation failed (1 term(s)):
    # task 'qm_task1' (evaluation 2): SCF calculation did not converge`, a
    # centre whose SCF never converged (recorded PASS in round
    # tmp_20261011_184226 with one frame written) -- and its wording merely
    # happens to contain an unconverged phrase. So the tolerance is scoped to
    # a `failed:` status whose own text carries one of the signatures.
    text = status_value.strip().lower()
    if not text.startswith('failed:'):
        return False
    text = text[len('failed:'):].strip()
    return any(signature in text for signature in _NOT_CONVERGED_SIGNATURES)


def closing_status(lines):
    """The `Status: ...` a run's log closes with, or None when it carries none.

    Two writers spell one fact: a skill agent's log ends in `Status: ...`, a
    framework run's closing line is `PyRAI3MD End: <time> Total: <dt> Status:
    <status>`, which does not *start* with `Status:` - and a run that dies
    inside its own result printing writes neither, which is exactly how the
    openqp frequency failures looked (round tmp_20261011_085800: the log stops
    at the `Vibrational Frequency Analysis` banner, no closing line).

    One definition on purpose: the reader that judges a leg
    (`_check_skill_log_status`) and the verifier that counts budget stops from a
    round's products (`tools/verify.py`) have to agree on what the closing line
    says, or the count and the verdict would name different legs.
    """
    for entry in reversed(lines):
        stripped = entry.strip()
        if stripped.startswith('Status:'):
            return stripped[len('Status:'):].strip()
        match = re.search(r'\bStatus:\s*(.*)$', stripped)
        if stripped.startswith('PyRAI3MD End:') and match:
            return match.group(1).strip()
    return None


def _check_skill_log_status(result, input_file, base_dir=None, title=''):
    """Verify the skill agent's own Status line in its log file.

    The run log is named after the job title and written into the
    directory the calculation ran in. Skill tests leave both anchors
    unset, so the log keeps being located beside the input file under
    the input stem (their title is that stem). Examples pass a
    ``base_dir`` and a ``title``: their artifacts land in the
    qualification run directory under ``control.title``, which differs
    from the source YAML stem (md_orca_fssh.yaml titles itself
    md_orca_fssh_example). The last line carries a ``Status: <outcome>``
    marker. When the log reports a failure or error, the result status
    is downgraded from 'pass' to 'fail' and the error message is
    recorded.

    Parameters
    ----------
    result : dict
        Test result dictionary (modified in place).
    input_file : str
        Path to the skill config/input file; its basename without
        extension locates the log when no title is given.
    base_dir : str, optional
        Directory holding the run's artifacts; defaults to the
        directory of ``input_file``.
    title : str, optional
        Run title naming the log; defaults to the ``input_file`` stem.
    """
    if not input_file:
        return

    # A run's log is not one file name in this suite. A framework-driven leg
    # names it after the title the input declares (`<title>.log`, written in
    # the run directory), while a skill agent names it after the config file it
    # was handed (`<stem>.log`, written beside that config). Both have to be
    # found: looking only for `<stem>.log` in the run directory matched nothing
    # for skill cases, which left this check inert exactly where it matters --
    # an agent that swallows its exception exits 0, so the return code never
    # says anything (#321's success-word rule found nothing because of this).
    config_dir = os.path.dirname(input_file)
    run_dir = base_dir or config_dir or os.getcwd()
    stem = os.path.splitext(os.path.basename(input_file))[0]
    names = ([title] if title else []) + [stem]
    candidates = [os.path.join(run_dir, name + '.log') for name in names]
    if os.path.abspath(config_dir) != os.path.abspath(run_dir):
        candidates.append(os.path.join(config_dir, stem + '.log'))
    log_path = next((path for path in candidates if os.path.exists(path)),
                    None)

    if log_path is None:
        return

    try:
        with open(log_path, 'r', encoding='utf-8', errors='ignore') as f:
            lines = f.read().splitlines()
    except OSError:
        return

    # The status is the remainder of that one line: `nn_pes_skill/agent.py`
    # writes its training tables *after* the Status line, so swallowing the
    # tail would turn a successful training run into a failure. A traceback
    # therefore quotes as its first line here; the exception itself reaches
    # the report through the subprocess output the runner records beside it.
    # Two writers, two spellings of the same fact. A skill agent's log ends
    # in `Status: {safe_run(...)}`; a framework run's closing line is
    # `PyRAI3MD End: <time> Total: <dt> Status: <status>`, which does not
    # *start* with `Status:` -- and a run that dies inside its own result
    # printing never writes it at all, which is exactly how the openqp
    # frequency failures looked (round tmp_20261011_085800: the log stops at
    # the `Vibrational Frequency Analysis` banner, no closing line). So a
    # log that exists without any status line is an unfinished run, not a
    # silent pass.
    status_value = closing_status(lines)
    if status_value is None:
        status_value = '<no closing status: the run log ends unfinished>'
    if status_value in RUN_LOG_SUCCESS:
        return
    # The one tolerated exception, from the same table the non-zero exit code
    # path consults: a truncated test optimization is expected to stop
    # unconverged, and the run log says so as `Status: failed: Maximum
    # optimization steps reached`. Reading the framework's closing line at all
    # is what #328 added, and without this exemption it turned four
    # constraint-optimize examples (which passed rounds tmp_20261011_085800
    # and tmp_20261011_121148) red in tmp_20261011_152909 -- the tightening
    # overrode the PASS[NOT CONVERGED] policy that `_detect_not_converged`
    # implements. One definition of what is excused, consulted by both paths.
    if optimization_budget_stop(status_value):
        # The exemption is a verdict, not a silence. Until #399 this path
        # returned without saying anything, so the marker existed only on the
        # non-zero-exit route (`_detect_not_converged` below) - and every
        # variable-cell example of round `tmp_20261019_200652` (all 32 legs)
        # stopped on its `maxit`, exited 0, and read as a plain pass. A reader of
        # a cell verdict asks whether the search converged, so the same wording
        # is recorded here, plus a flag the round document and `tools/verify.py`
        # can count without parsing prose.
        result['not_converged'] = True
        result['details'] = (
            (result.get('details') or '')
            + '\n[NOT CONVERGED] geometry optimization stopped before '
              'convergence within the test step budget')
        return
    # The positive word is the only one that means a run passed. The rule
    # used to test for the negative words 'failed'/'error' instead, so a
    # traceback -- the shape an engine failure actually takes on this line --
    # walked through as a pass, and six cp2k and molcas cases rode that false
    # green in round tmp_20261010_133424 with byte-identical engine inputs.
    result['status'] = 'fail'
    result['stderr'] = status_value or '<empty Status>'
    result['details'] = ((result.get('details') or '') +
        f'\n[LOG STATUS] {status_value or "<empty Status>"}')


# NVE total energy is a constant of the motion, so the recorded Etot
# column bounds every integrator and backend parsing error. A coarse
# spread catches them all; the slope separates a systematic leak from
# the bounded oscillation velocity Verlet always shows, and needs
# enough frames to be meaningful.
# The band is velocity Verlet's bounded oscillation at the example's own
# time step, not a leak: measured in the test environment (2026-11-08) on the
# 60-atom TIP3P NVE fixture, 500 steps / 21 frames give 1.7319828e-3 on
# the resident path and 1.7319877e-3 on the subprocess path (Epot/Ekin
# differ by at most 1.8e-6 between them, Etot by 1.35e-7), and the
# 2000-step run gives 1.40079e-3. The old 1e-3 sat below that amplitude;
# the failure signatures this sentinel exists for are an order larger
# (a mis-assigned excited-state reference slides Etot by 7.0e-2, the
# historical zero-gradient case by 5.6e-2, and the 2026-10 nve_yaml leak
# by 8.8e-3), so 5e-3 keeps every one of them red with a ~2.9x margin
# over the measured oscillation.
ENERGY_TOLERANCES = {
    'etot_drift': 5.0e-3,
    'etot_drift_rate': 1.0e-5,
}
RATE_MIN_FRAMES = 50


def read_md_energies(path):
    """Read the time/Epot/Ekin/Etot columns of an md.energies file.

    Parameters
    ----------
    path : str
        Path to the ``*.md.energies`` record.

    Returns
    -------
    list of list of float
        One row per recorded frame; empty when the file is missing
        or carries no data line.
    """
    try:
        with open(path, 'r', encoding='utf-8', errors='ignore') as f:
            lines = f.read().splitlines()
    except OSError:
        return []

    rows = []
    for line in lines[1:]:
        parts = line.split()
        if len(parts) < 4:
            continue
        try:
            rows.append([float(value) for value in parts[:4]])
        except ValueError:
            continue
    return rows


def is_center_record(path):
    """True for a per-center frame record, `<title>.md.<n>.energies`.

    Such a file holds one cluster's own energy plus its own atoms' kinetic
    energy (`workflow/records/output.py::_write_center_files`). It is not a
    constant of the motion -- the composite propagates the cluster with
    forces coming from the whole system, so a center exchanges energy with
    the box by design -- and only the trajectory total,
    `<title>.md.energies`, is judged. The single definition is here because
    `tools/verify.py` recomputes the same merge from the artifacts and a
    second copy of the rule is how the two drift apart.
    """
    return bool(re.search(r'\.md\.\d+\.energies$', path))


def energy_conservation_metrics(rows):
    """Summarise the total-energy conservation of one trajectory.

    Parameters
    ----------
    rows : list of list of float
        Frames as returned by :func:`read_md_energies`.

    Returns
    -------
    dict
        Metric name to value; ``etot_drift_rate`` only appears once
        enough frames were recorded to separate a systematic leak
        from the Verlet oscillation.
    """
    etot = [row[3] for row in rows]
    metrics = {'etot_frames': float(len(etot))}
    if len(etot) < 2:
        return metrics

    metrics['etot_drift'] = max(etot) - min(etot)

    n = len(etot)
    if n >= RATE_MIN_FRAMES:
        # Least-squares slope of Etot against the frame index, in
        # Hartree per recorded frame.
        mean_x = (n - 1) / 2.0
        mean_y = sum(etot) / n
        variance = sum((i - mean_x) ** 2 for i in range(n))
        covariance = sum((i - mean_x) * (value - mean_y)
                         for i, value in enumerate(etot))
        if variance:
            metrics['etot_drift_rate'] = abs(covariance / variance)
    return metrics


def _load_yaml_spec(input_file):
    """Parse an example's own YAML, or None when it cannot be read.

    The post-run checks all need the same two facts from it (what the run
    declared about its cell and its ensemble), and each of them used to
    open the file themselves.
    """
    if not input_file or not input_file.endswith(('.yaml', '.yml')):
        return None
    try:
        with open(input_file, 'r', encoding='utf-8') as f:
            spec = yaml.safe_load(f)
    except (OSError, yaml.YAMLError):
        return None
    return spec if isinstance(spec, dict) else None


def read_pair_cutoffs(path):
    """Every real-space cutoff a LAMMPS ``pair_style`` line declares.

    ``pair_style hybrid lj/charmm/coul/long 9.0 10.0 10.0 buck/coul/long
    10.0`` puts its numbers after each sub-style name, so the cutoffs are
    the bare floats of the line: an inner switching distance and an outer
    cutoff, whichever spelling the style uses.
    """
    try:
        with open(path, 'r', encoding='utf-8', errors='ignore') as f:
            lines = f.read().split('\n')
    except OSError:
        return []
    for line in lines:
        stripped = line.strip()
        if not stripped.startswith('pair_style'):
            continue
        cutoffs = []
        for token in stripped.split()[1:]:
            try:
                cutoffs.append(float(token))
            except ValueError:
                continue
        return cutoffs
    return []


def _shortest_cell_axis(spec):
    """The shortest axis of an untilted cell, or None when there is none.

    A tilted cell has no axis that plays the role of "half the box"; its
    perpendicular widths are the number that matters, and finding them is
    more arithmetic than a trace like this is worth.
    """
    cell = ((spec or {}).get('molecule') or {}).get('cell') or []
    try:
        lengths = [float(value) for value in list(cell)[:3]]
        angles = [float(value) for value in list(cell)[3:6]]
    except (TypeError, ValueError):
        return None
    if len(lengths) < 3 or len(angles) < 3:
        return None
    if any(abs(angle - 90.0) > 1e-6 for angle in angles):
        return None
    return min(lengths)


def _check_minimum_image(result, input_file, base_dir=None, title=''):
    """Record a pair cutoff that does not fit in half the cell.

    The minimum-image rule says a pair interacts through its nearest copy
    only while the cutoff fits inside half of the shortest axis. Past that
    the same pair is counted through several periodic images and the
    neighbour list changes size as an atom crosses the half box, which is
    energy that nothing in the integrator is responsible for. The shipped
    force field is more demanding than the small box the examples equilibrate
    in, so the fact is stated and left to the force-field decision that owns
    it: a qualification suite must not turn an open physics choice into a
    wall of failures, and it must not hide the fact either.

    Parameters
    ----------
    result : dict
        Test result dictionary (modified in place).
    input_file : str
        Path to the example YAML declaring the cell.
    base_dir : str, optional
        Directory the run wrote its artifacts into.
    title : str, optional
        Run title, unused here: the trace reads the staged templates.
    """
    spec = _load_yaml_spec(input_file)
    if spec is None:
        return
    axis = _shortest_cell_axis(spec)
    if axis is None:
        return
    run_dir = _run_directory(base_dir, input_file)
    cutoffs = []
    # Recursive on purpose: the launch directory holds a staged copy of the
    # input deck, but the deck the engine actually read is the one the
    # backend wrote into its own calculation directory, and ff_model
    # regenerates that from the force-field model rather than copying the
    # staged file. A scratch-tree test proved the difference -- editing the
    # staged *.in.init left the calcdir at pair_style ... 9.0 10.0 10.0 --
    # so reading only the launch level can report a cutoff no engine used.
    # The largest cutoff found anywhere under the run is the one that
    # matters for the minimum-image rule.
    for path in sorted(glob.glob(os.path.join(run_dir, '**', '*.in.init'),
                                 recursive=True)):
        cutoffs.extend(read_pair_cutoffs(path))
    if not cutoffs:
        return
    cutoff = max(cutoffs)
    if cutoff <= axis / 2.0:
        return
    details = result.get('details') or ''
    result['details'] = details + (
        '\n[PBC] pair cutoff %.3f A exceeds half of the %.3f A cell '
        '(minimum image needs %.3f): pairs interact through more than one '
        'periodic image' % (cutoff, axis, axis / 2.0))


def _constraint_block(spec):
    """The declared constraint block of an example spec, or {}.

    `system_constraint` is the spelling an example YAML writes and `constraint`
    is the classic section name; both are the same flat keyword mapping, and the
    energy criterion needs the keywords, not the structured records.
    """
    for name in ('system_constraint', 'constraint'):
        block = (spec or {}).get(name)
        if isinstance(block, dict) and block:
            return block
    return {}


def _constraint_breaks_conservation(spec):
    """Why a constrained run's Etot is not a constant of the motion, or None.

    The microcanonical criterion asserts that a closed system's recorded total
    energy stays flat. Three of this subsystem's declared capabilities break the
    premise rather than the integrator, and each was measured on the run's own
    `.md.energies` before the rule was written:

    - a metadynamics record deposits a hill every `meta_pace` steps, so the
      potential the particles move in is changed from outside the trajectory.
      Measured 1.44e-02 Hartree (periodic Gaussian, 60 steps) and 6.10e-03
      (periodic RMSD), both over the 1e-03 band; the aperiodic Gaussian case
      reaches only 4.73e-04 over its 5 steps, so the exemption is stated on the
      construction and not on the size of the leak;
    - a parameter ramp (`*_start` / `*_end` / `*_delay` / `*_stop`) does the
      same thing on a schedule, which is what a compression test asks for. The
      sphere wall whose radius closes 2.8 to 2.0 over 300 steps measured
      7.09e-04, inside the band, and is exempt for the same reason;
    - a strict constraint whose velocity half is left off projects positions
      only. That is the documented default of `velocity_constraint`, and the
      cost of it is the band this criterion would call a failure: measured
      1.78e-03 Hartree over 5 steps aperiodic, 2.85e-03 for the resumed half of
      the restart pair against 4.64e-03 for its 8-step continuous control, and
      9.10e-02 over 600 steps in the water box, against 3.28e-04 with `rattle`
      on the same record.

    A static bias, a static wall or a freeze is conservative and stays judged:
    the same measurement gives 8.05e-05, 2.66e-04 and 3.75e-04 Hartree, all
    inside the declared band.

    Returning a reason does not let a run off: it is written into the record, so
    an unjudged run is visible as unjudged instead of passing on a criterion
    nothing planned for it.

    Parameters
    ----------
    spec : dict
        The parsed example YAML.

    Returns
    -------
    str or None
        Why the criterion does not apply, or None when it does.
    """
    block = _constraint_block(spec)
    if not block:
        return None
    keys = [str(key).lower() for key in block]
    if any(key.startswith('meta_') for key in keys):
        return ('metadynamics deposits a history potential as the run '
                'proceeds, so the recorded Etot is not a constant of the '
                'motion')
    if any(key.endswith(('_start', '_end', '_delay', '_stop'))
           for key in keys):
        return ('a parameter ramp changes the potential on a schedule, so the '
                'recorded Etot is not a constant of the motion')
    strict = [key for key in ('shake_bond', 'shake_bond_type', 'shake_angle',
                              'shake_dihedral') if key in keys]
    if strict:
        velocity = block.get('shake_vel')
        segments = velocity if isinstance(velocity, list) else [velocity]
        if not all(str(segment).lower() == 'rattle' for segment in segments):
            return ('the strict constraints project positions only '
                    '(`shake_vel` is not `rattle`), which injects energy at '
                    'every projection')
    return None


def _embedding_breaks_conservation(spec):
    """Why an embedded composite's Etot is not a constant, or None.

    The microcanonical criterion assumes the forces are the gradient of one
    potential. An embedded composite re-computes its environment charges every
    evaluation and answers the gradient at those fixed charges, so the
    charge-response term never enters the force. QMMM with one center has
    stayed inside the band on every shipped case, so it keeps the criterion;
    with several centers each field carries the others' charges and the term
    the force drops is the one that couples them. On the ONIOM side the same
    loss is measured with one center too: `multiscale_oniom2_orca_embedding_md`
    printed a 2.45e-3 Hartree band over three frames against the 1e-3 budget,
    because the outer quantum charges move between frames. A static
    `read_charge` field does not move and stays judged.

    Measured on `multicenter_qmmm_md.yaml` (20-water box, two centers, one
    fitted round per step, cold stage): three-frame Etot band 8.4e-3 Hartree
    with the zero tier, 9.7e-3 with one fitted round, against a 1e-3 budget -
    and the same record's kinetic energy alone swings 6.5e-3 over those three
    frames, so a three-frame band on this system measures the record's noise
    floor as much as it measures leakage. The per-frame components, the
    composite identity and the per-center bookkeeping are judged elsewhere and
    stay judged; returning a reason here writes "not judged" into the record
    rather than a pass.

    Parameters
    ----------
    spec : dict
        The parsed example YAML.

    Returns
    -------
    str or None
        Why the criterion does not apply, or None when it does.
    """
    control = spec.get('control') or {}
    molecule = spec.get('molecule') or {}
    multiscale = str(control.get('multiscale_type', '') or '').lower()
    if multiscale not in ('qmmm', 'oniom', ''):
        return None
    if not molecule.get('embedding'):
        return None
    # A static read_charge field does not move between frames, so the force
    # can still be read as one potential's gradient; keep judging it.
    if molecule.get('read_charge'):
        return None
    regions = molecule.get('highlevel') or []
    nested = bool(regions) and all(isinstance(item, (list, tuple))
                                   for item in regions)
    if multiscale == 'qmmm':
        if not nested or len(regions) < 2:
            return None
        return ('an ESPF-embedded composite re-fits each center\'s 0-order '
                'charges every evaluation and returns the gradient at fixed '
                'charges, so with several centers the response term that '
                'couples them is absent from the force and the recorded Etot '
                'is not a constant of the motion by construction')
    # ONIOM: only a high-level carrier that actually receives point charges
    # makes the field a moving, non-variational one. Whether a skill does is
    # its own declaration (`receives_environment_charges` in its manifest),
    # so a second charge-receiving skill joins this judgement with no edit
    # here and a skill that writes no field keeps the criterion.
    from pyrai3md.skills.query import manifest_value

    theory = control.get('theory') or []
    high = str(theory[0]).strip().lower() if theory else ''
    if not manifest_value(high, 'receives_environment_charges', False):
        return None
    return ('an electrostatically embedded ONIOM composite re-computes its '
            'outer/mid charges every evaluation and returns the gradient at '
            'those fixed charges, so the charge-response term is absent from '
            'the force and the recorded Etot is not a constant of the motion '
            'by construction')


def _check_energy_conservation(result, input_file, config, base_dir=None,
                               title='', mode=''):
    """Judge NVE total-energy conservation from the recorded frames.

    Only microcanonical MD examples are judged: a thermostat or a
    barostat does work on the system, so Etot is meant to move there.
    The trajectory total is what is judged -- for a fan-out run one file
    per trajectory, merged by taking the largest value of each metric --
    and a violation downgrades a passing result to a failure. A
    multicentre run's per-center records are read but not judged: only the
    composite is a closed system. Which metric decides depends on how many
    frames were recorded: a short run can only be judged on the band it
    shows (max minus min), while a run of
    ``RATE_MIN_FRAMES`` or more is judged on the slope of Etot against the
    frame index, with the band kept in the record as context.

    Parameters
    ----------
    result : dict
        Test result dictionary (modified in place).
    input_file : str
        Path to the example YAML; its directory holds the records
        unless ``base_dir`` says otherwise.
    config : dict
        Parsed pmd_env.yaml configuration (optional ``energy`` keys).
    base_dir : str, optional
        Directory the run wrote its artifacts into; defaults to the
        directory of ``input_file``.
    title : str, optional
        Run title naming the records; defaults to the ``input_file``
        stem.
    mode : str, optional
        Qualification mode of the task ('benchmark' for a calibration
        leg), which decides whether this check applies at all.
    """
    if mode == 'benchmark':
        # A calibration leg is not an example run. Its verdict is the
        # population comparison the benchmark module computes (and prints
        # metric by metric right under this block); this check would look
        # for the example's frame records beside the reference input, where
        # by construction there are none, and report that as "no records"
        # on all 25 calibrations. Say what is not being judged and why.
        result['details'] = ((result.get('details') or '') +
                             '\n[ENERGY CONSERVATION] not judged for a '
                             'benchmark leg: the verdict is the reference '
                             'population comparison')
        return

    if not input_file or not input_file.endswith(('.yaml', '.yml')):
        return

    spec = _load_yaml_spec(input_file)
    if spec is None or (spec.get('control') or {}).get('jobtype') != 'md':
        return

    md = spec.get('md') or {}
    ensemble = str(md.get('ensemble', 'nve')).lower()
    thermostat = str(md.get('thermostat', 'off') or 'off').lower()
    if ensemble != 'nve' or thermostat not in ('off', 'none'):
        # State that this judgement did not run instead of returning
        # silently: a pass that reads identically whether it was judged or
        # not is not a verdict, which is the rule #246 established for the
        # band-versus-slope case and this branch had never been brought
        # under it. Only microcanonical runs are judged here; an NVT or NPT
        # record is read by `_check_npt_stability` on its cell instead.
        driven = ['ensemble %s' % ensemble]
        if thermostat not in ('off', 'none'):
            driven.append('thermostat %s' % thermostat)
        run_dir = _run_directory(base_dir, input_file)
        result['details'] = ((result.get('details') or '') +
            f'\n[ENERGY CONSERVATION] not judged under {run_dir}: this run '
            f'is driven by {" and ".join(driven)}, which does work on the '
            f'system, so the recorded Etot is not a constant of the motion')
        return

    # A run that declares a constraint which pumps energy by construction is
    # not a closed system: state that in the record and leave the band alone.
    reason = _constraint_breaks_conservation(spec)
    if reason:
        run_dir = _run_directory(base_dir, input_file)
        result['details'] = ((result.get('details') or '') +
            f'\n[ENERGY CONSERVATION] not judged under {run_dir}: {reason}')
        return

    reason = _embedding_breaks_conservation(spec)
    if reason:
        run_dir = _run_directory(base_dir, input_file)
        result['details'] = ((result.get('details') or '') +
            f'\n[ENERGY CONSERVATION] not judged under {run_dir}: {reason}')
        return

    run_dir = _run_directory(base_dir, input_file)
    stem = title or os.path.splitext(os.path.basename(input_file))[0]
    # Frame records are <title>.md.energies plus one per layer of a
    # multicentre run; the <title>.sh.energies hop records are sparse
    # by construction and stay out of the judgement. A fan-out run
    # (ninitcond > 1) writes no record at the level the task was launched
    # from: the runtime allocates one directory per trajectory,
    # <title>_1 ... <title>_n, and the frames go inside. Those are read too,
    # because otherwise md_parallel and md_batch report an unjudged verdict
    # over records that are plainly there. The search is deliberately not
    # recursive: an open-ended walk would also pick up a scratch tree or a
    # stale directory left by an earlier round and blend its frames into the
    # worst case being reported.
    patterns = [os.path.join(run_dir, f'{stem}*.energies'),
                os.path.join(run_dir, f'{stem}_*', f'{stem}*.energies')]
    paths = sorted(path for pattern in patterns
                   for path in glob.glob(pattern)
                   if re.search(r'\.md(\.\d+)?\.energies$', path))
    if not paths:
        # Leaving no trace here once hid the whole verdict: a run that
        # wrote no frame records is reported as unjudged instead of
        # passing silently.
        result['details'] = (result.get('details') or '') + (
            f'\n[ENERGY CHECK] no {stem}.md.energies under {run_dir}')
        return

    # Of those records only `<title>.md.energies` is a constant of the
    # motion. A multi-center run also writes `<title>.md.<c>.energies`
    # per center (`workflow/records/output.py::_write_center_files`), and
    # what that file holds is the center's own energy plus the kinetic
    # energy of its own atoms -- a region's contribution to the composite,
    # which the composite propagates by forces coming from the whole
    # system. A center is not a closed subsystem: energy flows between it
    # and the box every step by design, and only the sum is conserved.
    # Measured on examples/multicenter_pbc_nve.yaml over 60 recorded
    # frames: composite rate 2.906e-06 Ha/frame against a 1.0e-05
    # tolerance, while center 1 -- the water torn across the z face --
    # sweeps 8.82e-03 Ha of its own band at 4.279e-05 Ha/frame. Taking the
    # worst value over every file therefore judged a quantity that is not
    # conserved, and failed a run whose total was flat. The per-center
    # records stay in the report as `etot_center_drift`, the widest band
    # of the set, because how much a center exchanges is worth reading --
    # it just does not decide anything.
    totals = [path for path in paths if not is_center_record(path)]
    centers = [path for path in paths if is_center_record(path)]
    if not totals:
        result['details'] = (result.get('details') or '') + (
            f'\n[ENERGY CHECK] only the {len(centers)} per-center records '
            f'of {stem} were found under {run_dir}; no trajectory total to '
            f'judge')
        return

    tolerances = dict(ENERGY_TOLERANCES)
    tolerances.update((config or {}).get('energy') or {})

    merged = {}
    for path in totals:
        for name, value in energy_conservation_metrics(
                read_md_energies(path)).items():
            merged[name] = max(merged.get(name, value), value)
    if centers:
        merged['etot_center_drift'] = max(
            energy_conservation_metrics(
                read_md_energies(path)).get('etot_drift', 0.0)
            for path in centers)

    judged = {name: value for name, value in merged.items()
              if name in tolerances}
    frames = merged.get('etot_frames', 0)
    by_rate = frames >= RATE_MIN_FRAMES and 'etot_drift_rate' in merged
    if by_rate:
        # A long record judges on the slope, not on max minus min. Over a
        # handful of frames the two say something different; over a
        # thousand, max minus min is dominated by the bounded exchange
        # between kinetic and potential energy that a symplectic
        # integrator always shows, and it cannot tell that exchange from
        # energy actually leaving the system. The measured NVE example is
        # the case in point: 2.004e-03 Hartree of band against a
        # 3.36e-08 Hartree-per-frame slope, with the band as wide in its
        # second half as in its first, which is oscillation, not leakage.
        # The amplitude stays in the record below, so nothing is hidden;
        # it simply no longer decides the verdict on its own.
        judged.pop('etot_drift', None)
    result['metrics'] = {
        'metrics': merged,
        'tolerances': {name: tolerances[name] for name in judged},
    }

    exceeded = [(name, value, tolerances[name])
                for name, value in judged.items() if value > tolerances[name]]
    if exceeded and result.get('status') == 'pass':
        name, value, tolerance = exceeded[0]
        result['status'] = 'fail'
        result['details'] = ((result.get('details') or '') +
            f'\n[ENERGY CONSERVATION] {name} {value:.3e} exceeds '
            f'tolerance {tolerance:.3e}')
    elif by_rate:
        result['details'] = (result.get('details') or '') + (
            f'\n[ENERGY CONSERVATION] judged on {frames:.0f} frames: '
            f'etot_drift_rate {merged["etot_drift_rate"]:.3e} against '
            f'tolerance {tolerances["etot_drift_rate"]:.3e}; recorded '
            f'etot_drift (max-min) {merged["etot_drift"]:.3e}')
    elif frames and result.get('status') == 'pass':
        # The band decided, and the record says so. A 21-frame example
        # sits under RATE_MIN_FRAMES, which means the verdict is the
        # width of the oscillation and not a slope -- 9.740e-04 against
        # a 1e-3 tolerance is a 2.6% margin, and a reader is entitled to
        # know that the number which passed it was the loose one.
        result['details'] = (result.get('details') or '') + (
            f'\n[ENERGY CONSERVATION] judged on {frames:.0f} frames by '
            f'band: etot_drift {merged["etot_drift"]:.3e} against '
            f'tolerance {tolerances["etot_drift"]:.3e} '
            f'(rate needs {RATE_MIN_FRAMES} frames)')


# Isobaric-isothermal runs are judged on the cell, not on the energy:
