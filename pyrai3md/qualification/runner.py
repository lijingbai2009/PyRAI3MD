    # boxes within 16% of where they started, temperatures that drifted up
    # because the cell was doing work on the particles, which is ensemble
    # behaviour the integrator is not guilty of. What a code hole looks
    # like is the same round's csvr_pr at 3.1e6 K, and that still fails
    # (that pairing is no longer an example at all: schema/validate.py
    # refuses csvr with any extended-cell barostat, and the stochastic
