def read_md_lattice(path):
    """Read the per-frame cell matrices out of an md.xyz trajectory.

    Parameters
    ----------
    path : str
        Path to the ``*.md.xyz`` record.

    Returns
    -------
    list of list of float
        One flat nine-element row per frame, in file order; empty when
        the file is missing or writes no Lattice= comment.
    """
    lattices = []
    try:
        with open(path, 'r', encoding='utf-8', errors='ignore') as handle:
            for line in handle:
                start = line.find('Lattice="')
                if start < 0:
                    continue
                tail = line[start + len('Lattice="'):]
                end = tail.find('"')
                if end < 0:
                    continue
                values = tail[:end].split()
                if len(values) == 9:
                    lattices.append([float(value) for value in values])
    except (OSError, ValueError):
        return []
    return lattices


def read_md_ensemble(path, names):
    """Read named columns out of an md.ensemble table.

    Parameters
    ----------
    path : str
        Path to the ``*.md.ensemble`` record.
    names : tuple of str
        Column names to keep, exactly as their header spells them.

    Returns
    -------
    dict
        Column name to list of float; a non-numeric cell becomes NaN and
        a missing file or column yields nothing for that name.
    """
    try:
        with open(path, 'r', encoding='utf-8', errors='ignore') as handle:
            lines = [line for line in handle.read().splitlines()
                     if line.strip()]
    except OSError:
        return {}
    if len(lines) < 2:
        return {}
    header = lines[0].split()
    wanted = {name: index for index, name in enumerate(header)
              if name in names}
    columns = {name: [] for name in wanted}
    for line in lines[1:]:
        parts = line.split()
        for name, index in wanted.items():
            if index >= len(parts):
                continue
            try:
                columns[name].append(float(parts[index]))
            except ValueError:
                columns[name].append(float('nan'))
    return columns


def cell_frame_metrics(lattices, ensemble, temperature):
    """Summarise how far one NPT trajectory took the cell out of place.

    Parameters
    ----------
    lattices : list of list of float
        Flat nine-element cell rows from :func:`read_md_lattice`.
    ensemble : dict
        Columns from :func:`read_md_ensemble`; ``T_inst(K)`` is used for
        the temperature metric when present.
    temperature : float
        The target temperature the example declared.

    Returns
    -------
    dict
        ``cell_frames`` always; ``volume_drift`` (max |V/V0 - 1|),
        ``cell_rotation_rad`` (the summed polar angle between
        consecutive cells) from two frames up, and ``temperature_drift``
        (max |T_inst/T_target - 1|, first frame excluded because the
        run has not equilibrated its velocities yet).
    """
    metrics = {'cell_frames': float(len(lattices))}
    if len(lattices) < 2:
        return metrics
    volumes = []
    for row in lattices:
        matrix = [row[0:3], row[3:6], row[6:9]]
        volumes.append(abs(_determinant(matrix)))
    if volumes[0] <= 0.0:
        return metrics
    metrics['volume_drift'] = max(abs(value / volumes[0] - 1.0)
                                  for value in volumes)
    metrics['cell_rotation_rad'] = sum(
        _frame_rotation(lattices[index], lattices[index + 1])
        for index in range(len(lattices) - 1))
    temperatures = (ensemble or {}).get('T_inst(K)') or []
    if temperatures and temperature:
        metrics['temperature_drift'] = max(
            abs(value / temperature - 1.0) for value in temperatures[1:])
    return metrics


def _determinant(matrix):
    """Determinant of a 3x3 cell given as three rows of floats."""
    a, b, c = matrix[0]
    d, e, f = matrix[1]
    g, h, i = matrix[2]
    return a * (e * i - f * h) - b * (d * i - f * g) + c * (d * h - e * g)


def _frame_rotation(row_before, row_after):
    """Angle the simulation frame turned through between two frames.

    The affine map a step applies to the cell is
    ``lattice_after @ inverse(lattice_before)``; its polar orthogonal
    factor is the change of frame the re-triangularization committed,
    and ``arccos((trace - 1) / 2)`` is the angle of that rotation. A run
    whose cell never re-triangularizes sums to exactly zero, which is
    what makes this a measure of the NPT path and not of the box.
    """
    before = [row_before[0:3], row_before[3:6], row_before[6:9]]
    after = [row_after[0:3], row_after[3:6], row_after[6:9]]
    inverse = _invert3(before)
    if inverse is None:
        # A cell that stopped enclosing volume has no frame to compare
        # against; reporting that as an unbounded turn is the verdict,
        # not a crash on the way to it.
        return float('inf')
    matrix = _multiply(after, inverse)
    # The orthogonal factor of the polar decomposition is the closest
    # rotation to the deformation: U V^T from the SVD, computed here by
    # the Newton-Schulz iteration a 3x3 matrix converges in a few steps.
    polar = _orthogonal_factor(matrix)
    trace = max(-3.0, min(3.0, polar[0][0] + polar[1][1] + polar[2][2]))
    return math.acos(max(-1.0, min(1.0, (trace - 1.0) / 2.0)))


def _multiply(a, b):
    """Product of two 3x3 row-major matrices of floats."""
    return [[sum(a[row][k] * b[k][column] for k in range(3))
             for column in range(3)] for row in range(3)]


def _invert3(matrix):
    """Inverse of a 3x3 matrix by its adjugate, or None if singular.

    The qualification runner does not import numpy (it orchestrates
    remote work from plain text), so the 3x3 algebra a cell judgement
    needs is written out: determinant, adjugate, and the polar factor by
    iteration. Each of these three is checked against numpy in
    test_npt_stability.py, because a hand-rolled inverse that is
    silently transposed will report a cell as turning when it only
    sheared.
    """
    a, b, c = matrix[0]
    d, e, f = matrix[1]
    g, h, i = matrix[2]
    det = a * (e * i - f * h) - b * (d * i - f * g) + c * (d * h - e * g)
    if abs(det) < 1e-30:
        return None
    adjugate = [
        [(e * i - f * h), (c * h - b * i), (b * f - c * e)],
        [(f * g - d * i), (a * i - c * g), (c * d - a * f)],
        [(d * h - e * g), (b * g - a * h), (a * e - b * d)],
    ]
    return [[value / det for value in row] for row in adjugate]


def _transpose(matrix):
    """Transpose of a 3x3 row-major matrix."""
    return [[matrix[row][column] for row in range(3)] for column in range(3)]


def _orthogonal_factor(matrix):
    """Polar orthogonal factor of a 3x3 matrix by Newton-Schulz.

    ``X_{k+1} = 1.5 X_k - 0.5 X_k X_k^T X_k`` from ``X_0 = A / ||A||_F``
    converges to the closest orthogonal matrix, which is what the polar
    decomposition's U V^T is. numpy is not an import the qualification
    runner takes on for one angle, so the iteration is written out.
    """
    norm = math.sqrt(sum(value * value for row in matrix for value in row))
    if norm <= 0.0:
        return [[1.0 if row == column else 0.0 for column in range(3)]
                for row in range(3)]
    work = [[value / norm for value in row] for row in matrix]
    for _ in range(24):
        product = _multiply(_multiply(work, _transpose(work)), work)
        work = [[1.5 * work[row][column] - 0.5 * product[row][column]
                 for column in range(3)] for row in range(3)]
    return work


def _check_run_diagnostics(result, input_file, base_dir=None, title=''):
    """Surface what the run's own monitors saw, even when nothing failed.

    A violation of the accumulated-strain bound interrupts only a run that
    was started as a test (control.debug); otherwise the monitor reports
    and the trajectory continues, and the run then passes with no trace of
    having been watched. The findings live in <title>.log as '[DIAG ...]'
    lines, and the closing summary line states how often each check fired
    and when it first did -- which is the difference between "the box held"
    and "nobody looked".

    Parameters
    ----------
    result : dict
        Test result dictionary (modified in place).
    input_file : str
        Path to the example YAML; its directory locates the log.
    base_dir : str, optional
        Directory the run wrote its artifacts into.
    title : str, optional
        Run title naming the log.
    """
    if not input_file:
        return
    log_dir = base_dir or os.path.dirname(input_file) or os.getcwd()
    stem = title or os.path.splitext(os.path.basename(input_file))[0]
    log_path = os.path.join(log_dir, stem + '.log')
    if not os.path.exists(log_path):
        return
    try:
        with open(log_path, 'r', encoding='utf-8', errors='ignore') as f:
            lines = [line.strip() for line in f
                     if line.strip().startswith('[DIAG')]
    except OSError:
        return
    if not lines:
        return
    # Findings are one per check plus the summary; cap the echo so a long
    # log cannot dominate the record.
    shown = lines[:8]
    if len(lines) > len(shown):
        shown.append('[DIAG] ... %d further monitor line(s) in %s'
                     % (len(lines) - len(shown), stem + '.log'))
    result['details'] = ((result.get('details') or '') +
                         '\n' + '\n'.join(shown))


def _check_npt_stability(result, input_file, config, base_dir=None, title=''):
    """Judge an NPT example on what its cell did, not on its energy.

    Four of the eight NPT examples of the 2026-09-28 run passed while
    their boxes were deforming: one ended with a 1.66 Angstrom axis and a
    57% smaller volume, another turned its simulation frame by 28 degrees.
    Nothing in the suite noticed, because the only trajectory judgement
    that existed was the microcanonical one, which deliberately skips
    anything with a barostat. This is the judgement that gap left out.

    A violation downgrades a passing result, and a run that merely drifts
    far enough to be worth reading about gets a trace instead. The frame
    count is always stated: a 21-frame record is evidence about the first
    2 ps, and a reader should not have to work that out from the file.

    Parameters
    ----------
    result : dict
        Test result dictionary (modified in place).
    input_file : str
        Path to the example YAML.
    config : dict
        Parsed pmd_env.yaml configuration (optional ``box`` keys).
    base_dir : str, optional
        Directory the run wrote its artifacts into.
    title : str, optional
        Run title naming the records.
    """
    if not input_file or not input_file.endswith(('.yaml', '.yml')):
        return
    spec = _load_yaml_spec(input_file)
    if spec is None or (spec.get('control') or {}).get('jobtype') != 'md':
        return
    md = spec.get('md') or {}
    if str(md.get('ensemble', 'nve')).lower() != 'npt':
        return

    if result.get('status') != 'pass':
        # An error or an existing failure owns its message. Nothing this
        # judgement could add changes that the run already did not work,
        # and a dead engine leaves a truncated trajectory behind that
        # would read as a divergence of its own.
        return
    run_dir = _run_directory(base_dir, input_file)
    stem = title or os.path.splitext(os.path.basename(input_file))[0]
    # Same one-level trajectory rule as the energy check.
    xyz_patterns = [os.path.join(run_dir, f'{stem}*.md.xyz'),
                    os.path.join(run_dir, f'{stem}_*', f'{stem}*.md.xyz')]
    paths = sorted(path for pattern in xyz_patterns
                   for path in glob.glob(pattern)
                   if re.search(r'\.md(\.\d+)?\.xyz$', path))
    if not paths:
        result['details'] = (result.get('details') or '') + (
            f'\n[NPT CHECK] no {stem}.md.xyz under {run_dir}')
        return

    tolerances = dict(BOX_TOLERANCES)
    tolerances.update((config or {}).get('box') or {})
    notes = dict(BOX_NOTES)
    notes.update((config or {}).get('box_notes') or {})

    merged = {}
    for path in paths:
        metrics = cell_frame_metrics(
            read_md_lattice(path),
            read_md_ensemble(path.replace('.xyz', '.ensemble'),
                             ('T_inst(K)',)),
            float(md.get('temperature', 0.0) or 0.0))
        for name, value in metrics.items():
            merged[name] = max(merged.get(name, value), value)

    frames = merged.get('cell_frames', 0)
    if frames < 2:
        result['details'] = (result.get('details') or '') + (
            f'\n[NPT STABILITY] unjudged, {frames:.0f} cell frames '
            f'recorded in {len(paths)} trajectory file(s)')
        return

    judged = {name: merged[name] for name in tolerances if name in merged}
    result['box_metrics'] = {'metrics': merged,
                             'tolerances': dict(tolerances)}
    exceeded = [(name, value, tolerances[name])
                for name, value in judged.items() if value > tolerances[name]]
    summary = ('volume_drift %.3f, temperature_drift %.3f, '
               'cell_rotation_rad %.3f over %d cell frames'
               % (merged.get('volume_drift', float('nan')),
                  merged.get('temperature_drift', float('nan')),
                  merged.get('cell_rotation_rad', 0.0), frames))
    if exceeded and result.get('status') == 'pass':
        name, value, tolerance = exceeded[0]
        result['status'] = 'fail'
        result['details'] = ((result.get('details') or '') +
            f'\n[NPT STABILITY] {name} {value:.3f} exceeds tolerance '
            f'{tolerance:.3f} ({summary})')
        return
    flagged = [(name, value, notes[name]) for name, value in merged.items()
               if name in notes and value > notes[name]]
    trace = ' '.join('%s %.3f over %.3f; ' % item for item in flagged)
    result['details'] = (result.get('details') or '') + (
        f'\n[NPT STABILITY] {trace if trace else ""}all cell thresholds '
        f'held ({summary})')



def read_optimize_tail(log_path, keep='last'):
    """An optimization-progress block of a run log, as named rows.

    The rows are read by the titles `kernel/logger.py::log_optimize_step`
    prints them with. `keep='last'` (the default) lets the last block win: the
    judgment a run is graded on is the state it stopped in. `keep='first'`
    returns the first block instead, which is where a direction test gets its
    starting point - the state before the search moved anything. Returns nothing
    when the file holds no such block, which the caller reports as unjudged
    rather than as a zero - an absent row and a row that says zero bar are two
    different facts.
    """
    try:
        with open(log_path, 'r', encoding='utf-8', errors='ignore') as handle:
            lines = handle.read().splitlines()
    except OSError:
        return {}
    tail = {}
    seen = False
    for line in lines:
        head, separator, rest = line.partition(':')
        if not separator:
            continue
        key = head.strip()
        if key not in OPTIMIZE_TAIL_KEYS:
            continue
        if keep == 'first' and key in tail:
            continue
        fields = rest.split()
        if not fields:
            continue
        if key == 'Converged':
            tail[key] = (fields[0] == 'True')
        else:
            try:
                tail[key] = float(fields[0])
            except ValueError:
                continue
        seen = True
    return tail if seen else {}


# The smallest shape change a real leg has been measured to make, and the
# floor it has to clear. `opt_geom.xyz` writes its cell to six decimals, so
# three independently rounded lengths jitter their ratios around 1e-7; the floor
# sits two orders above that. Measured over round tmp_20261018_082139's own
# trajectories, every one of which ran `anisotropic`: cp2k 9.7e-05 (its two-step
# budget, the tightest of them), xtb 1.4e-04, lammps 2.9e-04,
# `meci_multiscale` 4.5e-04, ts 2.9e-03. The declared-isotropic leg of the same
# round left its ratios at exactly 0.0e+00 while all three rows shrank from
# 10.000000 to 9.976689 A, which is the other arm and the reason the floor is
# not a compromise between two readings that overlap.
CELL_SHAPE_FLOOR = 1.0e-5


def row_length_ratios(lattice):
    """The two shape ratios of one nine-element cell row, or None.

    A box is a volume and a shape, and the `volume` column of the status record
    carries only the first: a run that inflated its three rows together and a run
    that stretched one of them print the same number. The ratios of the row
    lengths are the half that is left, and a degenerate row reads as None rather
    than as an infinite ratio.
    """
    lengths = [math.sqrt(sum(float(value) ** 2
                             for value in lattice[index:index + 3]))
               for index in (0, 3, 6)]
    if min(lengths) <= 0.0:
        return None
    return (lengths[0] / lengths[1], lengths[0] / lengths[2])


def _check_cell_shape(result, params, run_dir):
    """Judge the declared cell coupling against the shape the box took.

    `opt_cell_coupling` decides one thing and one thing only: whether the
    lattice half of a step is confined to the single direction that scales all
    three rows together (`optimizer/base.py::_cell_direction`, :757-780, which
    returns that unit vector for `isotropic` and None for `anisotropic`). Both
    choices move the box, so the volume drift the cell columns already prove
    cannot tell them apart, and neither can the convergence report, which reads
    the same conjugate force either way. The trajectory's own `Lattice=`
    comments can, because the isotropic direction leaves the ratios of the row
    lengths exactly where it found them.

    A change below `CELL_SHAPE_FLOOR` reads as no shape change at all, and the
    measured number is printed whichever way the verdict goes: a run with
    genuinely little anisotropy in it shows its own reading instead of hiding
    behind a pass.
    """
    lattices = read_md_lattice(os.path.join(run_dir, 'opt_geom.xyz'))
    if len(lattices) < 2:
        result['details'] = ((result.get('details') or '') +
            '\n[COUPLING] unjudged: %d frame(s) of opt_geom.xyz '
            'carry a Lattice= comment, and a shape needs a first and a last one'
            % len(lattices))
        return
    first = row_length_ratios(lattices[0])
    last = row_length_ratios(lattices[-1])
    if first is None or last is None:
        result['details'] = ((result.get('details') or '') +
            '\n[COUPLING] unjudged: a frame of opt_geom.xyz has a '
            'zero lattice row in it, so its ratios are not a shape')
        return
    change = max(abs(last[0] / first[0] - 1.0), abs(last[1] / first[1] - 1.0))
    declared = str(params.get('opt_cell_coupling') or 'anisotropic').lower()
    result.setdefault('cell_metrics', {})['shape_ratio_change'] = change
    if declared == 'isotropic':
        if change > CELL_SHAPE_FLOOR:
            result['status'] = 'fail'
            result['details'] = ((result.get('details') or '') +
                '\n[COUPLING] the run declares isotropic coupling but its '
                'lattice row-length ratios moved by %.3e over %d frames (first '
                '%s, last %s): one direction that scales the three rows '
                'together leaves them where it found them, so the step was not '
                'confined to it' % (change, len(lattices), first, last))
            return
    elif change <= CELL_SHAPE_FLOOR:
        result['status'] = 'fail'
        result['details'] = ((result.get('details') or '') +
            '\n[COUPLING] the run declares anisotropic coupling (or takes '
            'the default) and its lattice kept its shape to %.3e over %d frames '
            '(first %s, last %s): an unprojected step answers the three '
            'components separately, and a box that stayed proportionate is the '
            'signature of the isotropic direction still being applied'
            % (change, len(lattices), first, last))
        return
    result['details'] = ((result.get('details') or '') +
        '\n[COUPLING] %s coupling agrees with the box: row-length ratios '
        'moved by %.3e over %d frames' % (declared, change, len(lattices)))


def _check_path_cell_record(result, run_dir, method):
    """Judge a variable-cell *path* run on its own convergence record.

    The two readings `check_cell_optimization` takes off `opt_status.txt` are
    taken here off `path_status.txt`, whose header carries the same five cell
    column names (`utilities/opt_formatter.py::STATUS_CELL_COLUMNS`): the columns
    must be present, which says the switch reached the walk, and the volume must
    differ between the first and the last row, which says the box moved. The
    third reading that check takes - the shape the box took against
    `opt_cell_coupling` - is not carried over: it reads a trajectory's own
    `Lattice=` comments through `_check_cell_shape`, and pointing that at a
    path record is a separate measurement rather than a rename of this one.
    """
    record = os.path.join(run_dir, 'path_status.txt')
    if not os.path.exists(record):
        result['status'] = 'fail'
        result['details'] = ((result.get('details') or '') +
            '\n[CELL] no path_status.txt under %s: optimize.method %s declares '
            'optimize_cell, and a path run leaves its convergence record under '
            'that name - without it the switch can be neither confirmed nor '
            'denied' % (run_dir, method))
        return
    try:
        with open(record, 'r', encoding='utf-8') as handle:
            lines = [line.split() for line in handle.read().splitlines() if line.strip()]
    except OSError as exc:
        result['status'] = 'fail'
        result['details'] = ((result.get('details') or '') +
            '\n[CELL] path_status.txt at %s could not be read: %s' % (record, exc))
        return
    if not lines:
        result['status'] = 'fail'
        result['details'] = ((result.get('details') or '') +
            '\n[CELL] the record at %s is empty' % record)
        return
    header, rows = lines[0], lines[1:]
    missing = [name for name in STATUS_CELL_COLUMNS if name not in header]
    if missing:
        result['status'] = 'fail'
        result['details'] = ((result.get('details') or '') +
            '\n[CELL] the path record at %s has no cell columns %s (header: %s): '
            'they are printed only when the lattice is a variable, so their '
            'absence says the switch was dropped between the input and the walk'
            % (record, missing, ' '.join(header)))
        return
    index = header.index('volume')
    volumes = []
    for row in rows:
        if len(row) == len(header):
            try:
                volumes.append(float(row[index]))
            except ValueError:
                continue
    if len(volumes) < 2 or volumes[0] == volumes[-1]:
        result['status'] = 'fail'
        result['details'] = ((result.get('details') or '') +
            '\n[CELL] the path record at %s reads %s for the volume across %d '
            'row(s): a box that did not move was not relaxed'
            % (record, volumes, len(rows)))


def _adaptive_expectations(input_file, base_dir):
    """Read the iteration count and trajectory count the run asked for.

    The adaptive family is not uniform: the original carriers ask for two
    iterations and five trajectories, while the one-feature carriers use
    one or four iterations and two trajectories. The verdict reads the
    example's own configuration instead of pinning those numbers, so a
    feature carrier is judged on what it declared.
    """
    try:
        if str(input_file).lower().endswith(('.yaml', '.yml')):
            with open(input_file, encoding='utf-8') as handle:
                config = yaml.safe_load(handle)
        else:
            config = None
            directory = base_dir or os.path.dirname(input_file)
            for candidate in sorted(glob.glob(os.path.join(directory,
                                                           '*.json'))):
                try:
                    with open(candidate, encoding='utf-8') as handle:
                        data = json.load(handle)
                except (OSError, ValueError):
                    continue
                if isinstance(data, dict) and (
                        'maxiter' in data or 'adaptive' in data):
                    config = data
                    break
        if not isinstance(config, dict):
            return 2, 5
        adaptive = (config.get('adaptive')
                    if isinstance(config.get('adaptive'), dict) else config)
        dynamics = (config.get('md')
                    if isinstance(config.get('md'), dict) else config)
        maxiter = int(adaptive.get('maxiter') or 2)
        ninitcond = int(dynamics.get('ninitcond') or 5)
        return max(1, maxiter), max(1, ninitcond)
    except (OSError, TypeError, ValueError):
        return 2, 5


def _check_adaptive_products(result, input_file, base_dir=None, title=''):
    """Judge an adaptive example on its product tree.

    A zero exit is not a verdict for adaptive sampling: the workflow can
    finish with no selected frame, no reference labels or no trained
    model and still return 0. The summary and the product tree are the
    reading this check adds. A non-adaptive example writes no
    ``<title>.adaptive`` directory and is left alone.

    The iteration count and the per-iteration trajectory count are read
    from the example's own configuration: the original carriers ask for
    two iterations and five trajectories, the one-feature carriers for
    one or four iterations and two trajectories.
    """
    if not title:
        return
    root = os.path.join(base_dir or os.path.dirname(input_file),
                        '%s.adaptive' % title)
    if not os.path.isdir(root):
        return
    summary_path = os.path.join(root, '%s.adaptive.json' % title)
    expected_iterations, expected_trajectories = _adaptive_expectations(
        input_file, base_dir)
    problems = []
    if not os.path.isfile(summary_path):
        problems.append('missing %s' % os.path.basename(summary_path))
    else:
        try:
            with open(summary_path, encoding='utf-8') as handle:
                summary = json.load(handle)
        except (OSError, ValueError) as error:
            problems.append('unreadable adaptive summary: %s' % error)
            summary = {}
        n_iterations = int(summary.get('n_iterations') or 0)
        if n_iterations != expected_iterations:
            problems.append('n_iterations=%d (expected %d)'
                            % (n_iterations, expected_iterations))
    iter2_status = {}
    for iteration in range(1, expected_iterations + 1):
        status_path = os.path.join(
            root, 'iter-%d' % iteration, 'status_iter-%d.json' % iteration)
        if not os.path.isfile(status_path):
            problems.append('missing iter-%d status' % iteration)
            continue
        try:
            with open(status_path, encoding='utf-8') as handle:
                status = json.load(handle)
        except (OSError, ValueError) as error:
            problems.append('unreadable iter-%d status: %s'
                            % (iteration, error))
            continue
        if int(status.get('ntraj') or 0) != expected_trajectories:
            problems.append('iter-%d ntraj=%s (expected %d)'
                            % (iteration, status.get('ntraj'),
                               expected_trajectories))
        if iteration == 2:
            iter2_status = status
            if not status.get('reference_ran'):
                problems.append('iter-2 reference did not run')
            if not status.get('trained'):
                problems.append('iter-2 training did not run')
            if int(status.get('new_frames') or 0) < 1:
                problems.append('iter-2 produced no new reference frame')
    if expected_iterations >= 2:
        iter2 = os.path.join(root, 'iter-2')
        if not glob.glob(os.path.join(iter2, 'data_iter-2_*.json')):
            problems.append('missing iter-2 data snapshot')
        if not os.path.isfile(os.path.join(
                iter2, 'reference', 'new-samples.json')):
            problems.append('missing iter-2 reference labels')
        # The model directory the training wrote is recorded by the
        # adaptive workflow through the skill's own `model_dir_name`;
        # recomputing it here with a named skill would make this audit
        # the second owner of the naming rule (and the only one that has
        # to know which skill ran).
        model = str(iter2_status.get('modeldir') or '')
        if model and not os.path.isabs(model):
            model = os.path.join(iter2, model)
        if not model or not os.path.isdir(model):
            problems.append('missing iter-2 trained model')
    if problems:
        result['status'] = 'fail'
        result['details'] = '[ADAPTIVE] ' + '; '.join(problems)


def check_cell_optimization(result, input_file, base_dir=None, title=''):
    """Judge a variable-cell example on the things that can be read off disk.

    Nothing else in the suite asks whether `optimize_cell` arrived anywhere. The
    keyword is derived into a capability by the planning layer and read by the
    optimizer out of the flattened params, and a spelling invented between those
    two (an earlier revision prefixed it, `opt_optimize_cell`, and the run relaxed
    its atoms while its box sat still) leaves every other check green. Two
    measurements tell the difference, both on the framework's own product:

    - the status record must carry the cell columns. They are printed only when
      the lattice is a variable, so their absence says the switch was dropped;
    - the volume must differ between the first and the last recorded step. A run
      whose box never moved did not relax it, however quiet its atoms are;
    - the declared `opt_cell_coupling` must agree with the shape the box took,
      which `_check_cell_shape` reads off the trajectory's own `Lattice=`
      comments. A volume moves under either coupling, so without this third
      reading the keyword asks for one direction and is answered by another
      with nobody the wiser.

    The record is read through `utilities/print_results.py`, the writer's own table
    definition, so this judge cannot take an engine's convergence file (openqp
    writes one under this same plain name, with a different header) for a
    framework run. Lines that do not match the header are reported, not dropped:
    a truncated last row is how a killed run reads, and silently losing it would
    report a shorter relaxation than the run recorded.

    What is deliberately not judged here: the constraint multipliers and the
    frozen-atom ride are keys of the optimizer's in-memory report
    (`workflow/optimizer/base.py`) and reach no file, so a post-run check cannot
    read them. Those two rows are pinned by unit criteria instead.

    Parameters
    ----------
    result : dict
        Test result dictionary (modified in place).
    input_file : str
        Path to the example YAML declaring the switch.
    base_dir : str, optional
        Directory the run wrote its artifacts into.
    title : str, optional
        Run title, unused: the optimizer names its status record plainly.
    """
    if not input_file or not input_file.endswith(('.yaml', '.yml')):
        return
    spec = _load_yaml_spec(input_file)
    if spec is None or (spec.get('control') or {}).get('jobtype') != 'optimize':
        return
    params = spec.get('optimize') or {}
    if not params.get('optimize_cell'):
        return
    if result.get('status') != 'pass':
        # An error or an existing failure owns its message.
        return

    run_dir = _run_directory(base_dir, input_file)
    method = str(params.get('method') or '').strip().lower()
    if method in ('mep', 'irc', 'neb'):
        # A path run declares `optimize_cell` like any other search and reads it
        # the same way (`workflow/path.py` steps the joint vector through the
        # optimizer's own cell half), but its convergence record is
        # `path_status.txt`: the path tables are written by the Path workflow and
        # are not `utilities/print_results.py`'s table, so this judge's reader
        # cannot be the one that reads them. What it asks for is the same thing
        # though - the five cell columns and a box that moved - so it asks it
        # here, on the path's own record. Measured before this branch existed:
        # the four variable-cell path cases failed a whole round on "no
        # opt_status.txt", which a path run never writes by design.
        _check_path_cell_record(result, run_dir, method)
        return
    # The optimizer writes its convergence record into the directory the run was
    # started in, which is the leg directory here. Measured over every example of
    # a round: all 21 status records of tmp_20261015_100320 sit at
    # `<example>/<mode>/opt_status.txt` and none deeper, so this reads that one
    # location and a record elsewhere is reported as absent rather than guessed.
    path = os.path.join(run_dir, 'opt_status.txt')
    if not os.path.exists(path):
        result['status'] = 'fail'
        result['details'] = ((result.get('details') or '') +
            '\n[CELL] no opt_status.txt under %s: a run that declares '
            'optimize_cell has to leave its convergence record, and without it '
            'the switch can be neither confirmed nor denied' % run_dir)
        return

    try:
        record = read_status(path)
    except OSError as exc:
        result['status'] = 'fail'
        result['details'] = ((result.get('details') or '') +
            '\n[CELL] opt_status.txt at %s could not be read: %s'
            % (path, exc))
        return

    if record.writer == WRITER_FOREIGN:
        result['status'] = 'fail'
        result['details'] = ((result.get('details') or '') +
            '\n[CELL] the record at %s is not the framework table (header: %s). '
            'A run that declares optimize_cell has to leave its own convergence '
            'record; an engine writes one under this file name too, and reading '
            'it here would answer for a box the framework never moved'
            % (path, ' '.join(record.columns)))
        return

    missing = [name for name in STATUS_CELL_COLUMNS if name not in record.columns]
    if missing:
        result['status'] = 'fail'
        result['details'] = ((result.get('details') or '') +
            '\n[CELL] the run declares optimize_cell but its status record '
            'carries no %s column (header: %s). That is how a dropped switch '
            'reads: the atoms were relaxed and the box was left a constant'
            % (', '.join(missing), ' '.join(record.columns)))
        return

    rows = record.rows
    volumes = [row['volume'] for row in rows]
    if len(volumes) < 2:
        result['details'] = ((result.get('details') or '') +
            '\n[CELL] unjudged, %d step(s) recorded in %s%s'
            % (len(volumes), os.path.relpath(path, run_dir),
               format_malformed(record)))
        return
    drift = abs(float(volumes[-1]) - float(volumes[0]))
    last = rows[-1]
    result['cell_metrics'] = {
        'steps': len(rows),
        'volume_first': float(volumes[0]),
        'volume_last': float(volumes[-1]),
        'volume_drift': drift,
        'cell_grms': float(last.get('cell_grms', float('nan'))),
        'cell_gmax': float(last.get('cell_gmax', float('nan'))),
        'cell_drms': float(last.get('cell_drms', float('nan'))),
        'cell_dmax': float(last.get('cell_dmax', float('nan'))),
        'malformed_rows': len(record.malformed),
    }
    if drift <= 0.0 and result.get('status') == 'pass':
        result['status'] = 'fail'
        result['details'] = ((result.get('details') or '') +
            '\n[CELL] the box never moved: volume %.6f at step 1 and at step '
            '%d, over %d recorded steps. A variable-cell run whose lattice is '
            'unchanged relaxed its atoms only'
            % (volumes[0], len(rows), len(rows)))
        return
    result['details'] = ((result.get('details') or '') +
        '\n[CELL] cell columns present; volume moved %.6f over %d steps, '
        'final cell_gmax %.3e cell_grms %.3e%s'
        % (drift, len(rows), result['cell_metrics']['cell_gmax'],
           result['cell_metrics']['cell_grms'], format_malformed(record)))
    _check_cell_shape(result, params, run_dir)
    if result.get('status') != 'pass':
        # The shape verdict owns this finding. A pressure reading laid over a
        # box that moved along the wrong directions would answer a different
        # question than the one that just failed.
        return
    _check_cell_pressure(result, spec, params, run_dir, title,
                         float(volumes[0]), float(volumes[-1]))


def _engine_stems(config):
    """The engine list of a config, lowest to highest layer, whatever its shape.

    The input YAML spells `control.theory` a list and the round's flat config
    sometimes carries it as one space-separated string
    (`manager.py:954-960` accepts both when it resolves skills), so a comparison
    that reads only one shape silently matches nothing.
    """
    value = config.get('theory') if isinstance(config, dict) else None
    if isinstance(value, (list, tuple)):
        return tuple(str(item).strip().lower() for item in value
                     if str(item).strip())
    if isinstance(value, str) and value.strip():
        return tuple(value.split())
    return ()


def _natural_motion_of_the_same_box(run_dir, params, volume_first, theory=None):
    """The round's zero-pressure twin of this box, when the plan holds exactly one.

    A pressure can only be called the wrong way against something: the same
    optimizer, the same declared coupling, the same engine list and the same
    starting volume with `opt_pressure` absent is what that box does on its own.
    Round `tmp_20261018_200317` is why this exists - its loaded leg expanded (1157.625
    -> 1173.838 A^3) and the old clause read that as a sign error, while the same
    box with no load expanded further still (17.088 A^3 against 16.213 with 1 kbar
    on it): the load opposed the natural motion, which is what opposing looks like
    from a box that starts more compressed than the pressure applied.

    The engine list is part of the identity because a drift is a property of the
    scoring function, not of the box: two arms of one plan can share optimizer,
    coupling and starting volume while one is scored by xtb and the other by cp2k,
    and neither is the other's unstressed self.

    Returns
    -------
    tuple
        `(label, drift)` for a unique twin; `(None, None)` when the round holds
        none; `('ambiguous', count)` when it holds more than one. The last two are
        reported by the caller rather than resolved by a pick, because a direction
        claim resting on an arbitrary reference is not a measurement.
    """
    # `run_dir` is `<round>/examples/<example>/<carrier>`.
    examples_root = os.path.dirname(os.path.dirname(os.path.abspath(run_dir)))
    # The leg's own params come from the input YAML, which spells the optimizer
    # `method`; the round's flat config carries it as `opt_method`. Both sides of
    # the comparison accept either spelling, or the reference never matches.
    method = str(params.get('opt_method') or params.get('method') or '')
    coupling = str(params.get('opt_cell_coupling') or 'anisotropic').lower()
    engines = _engine_stems({'theory': theory} if theory is not None else params)
    found = {}
    for cfg_path in sorted(glob.glob(os.path.join(examples_root, '*', '*',
                                                  '*.json'))):
        leg_dir = os.path.dirname(cfg_path)
        if os.path.abspath(leg_dir) == os.path.abspath(run_dir):
            continue
        try:
            with open(cfg_path, 'r', encoding='utf-8') as handler:
                other = json.load(handler)
        except (OSError, ValueError):
            continue
        if not isinstance(other, dict) or not other.get('optimize_cell'):
            continue
        try:
            if float(other.get('opt_pressure') or 0.0):
                continue
        except (TypeError, ValueError):
            continue
        if str(other.get('opt_method') or other.get('method') or '') != method:
            continue
        if str(other.get('opt_cell_coupling')
               or 'anisotropic').lower() != coupling:
            continue
        # Same box, different scoring engine: not a twin. Declared by the caller
        # as the leg's own `control.theory`; when nothing is passed the key stays
        # whatever the round recorded, because a comparison against an unknown
        # engine list would reject every candidate and report "no twin".
        if engines and _engine_stems(other) != engines:
            continue
        status_path = os.path.join(leg_dir, 'opt_status.txt')
        if not os.path.isfile(status_path):
            continue
        try:
            record = read_status(status_path)
        except OSError:
            continue
        volumes = [row.get('volume') for row in record.rows]
        if len(volumes) < 2 or volumes[0] is None or volumes[-1] is None:
            continue
        if abs(float(volumes[0]) - float(volume_first)) > 1.0e-6:
            continue
        drift = abs(float(volumes[-1]) - float(volumes[0]))
        # Two arms of one example are compared, not averaged: their drifts count
        # as the one reference while they agree to within the tolerance this scan
        # already uses on the starting volume, and as two references once they
        # do not. A tenth-significant-digit difference is the same measurement;
        # a difference the size of the drift itself is the round holding two
        # different unstressed boxes under one name.
        kept = found.setdefault(
            os.path.basename(os.path.dirname(leg_dir)), [])
        if not any(abs(drift - other_drift)
                   <= 1.0e-6 * max(abs(other_drift), drift, 1.0)
                   for other_drift in kept):
            kept.append(drift)
    if not found:
        return None, None
    if len(found) > 1 or any(len(drifts) > 1 for drifts in found.values()):
        # Reported as a count of references, not of example names: the case this
        # clause exists for is one example whose two modes disagree, and "1 twin
        # is on the plan and choosing one is not a measurement" would be nonsense.
        return 'ambiguous', sum(len(drifts) for drifts in found.values())
    label = next(iter(found))
    return label, float(found[label][0])


def _check_cell_pressure(result, spec, params, run_dir, title,
                         volume_first, volume_last):
    """Judge a run under an applied pressure against that pressure.

    `opt_pressure` changes what the box is asked to stop at: the objective is
    `E + p V`, so the lattice is at rest where the stress equals `-p I`, and the
    two `Cell Stress` rows the framework prints are the residual of `sigma + p I`
    in bar - the numbers the run is judged on, not the raw engine stress. Before
    this clause a pressure leg was graded on the same two facts as any other
    variable-cell leg (the cell columns arrived, the box moved), and a run that
    stopped three steps into a 10 kbar compression - 9972.6 bar of residual still
    on the box, read off round tmp_20261017_094721's own products - passed it.
    Nothing in the suite asked.

    Two things are judged here, and a third pair is read off the same block and
    printed without being judged - all only for a leg that declares a nonzero
    pressure, because the other legs' budgets are capped on purpose and their
    verdict is about the machinery:

    - the keyword reached the optimizer: the block's `External Pressure` row must
      equal the declared one. A pressure dropped between the input and the
      search leaves the run relaxing `E`, not `E + p V`, and every other reading
      still looks sane;
    - the box moved toward its rest point. Two readings say so, and neither one
      guesses the direction from the sign of `opt_pressure`: the residual of
      `sigma + p I` has to come down from the first recorded step to the last,
      and - when the round carries a unique zero-pressure leg of this same box,
      engines, optimizer and coupling - the loaded drift has to be smaller than
      the drift that box makes unloaded. The clause used to assert that a positive pressure
      must shrink the volume, and round `tmp_20261018_200317` falsified it: this
      box starts far more compressed than 1 kbar, so its rest point lies at a
      LARGER volume, and a correct run was being reported as a sign error;
    - the endpoint residual and the convergence flag, which this package does
      NOT judge. Ruled on 2026-10-19 after round `tmp_20261019_122659`: these
      legs run at `maxit: 5`, a functional-test budget, and a five-step box
      cannot be failed for not having reached its band - the same round's own
      numbers say the target was right while the budget cut the path short (the
      isotropic leg's residual ran 10818.1 -> 9732.0 -> 6971.1 -> 181.5 ->
      1319.9 bar, so it crossed its rest point at 1168.87 A^3 on step 4 and the
      endpoint it was judged on was the rebound). What comes down from that is
      printed in the verdict as `NOT JUDGED`, with its numbers, because a
      reading withheld from the document is a reading nobody can re-check.
    """
    pressure = float(params.get('opt_pressure') or 0.0)
    if not pressure:
        return
    log_path = os.path.join(run_dir, '%s.log' % title) if title else ''
    tail = read_optimize_tail(log_path)
    if 'Cell Stress RMS' not in tail:
        result['details'] = ((result.get('details') or '') +
            '\n[CELL] pressure %.1f bar unjudged: %s carries no optimization-'
            'progress block with the Cell Stress rows, and the residual of '
            'sigma + p I cannot be read off anything else'
            % (pressure, os.path.join(run_dir, '%s.log' % title)))
        return
    rms = float(tail['Cell Stress RMS'])
    maximum = float(tail.get('Cell Stress Max', rms))
    stated = float(tail.get('External Pressure', float('nan')))
    first = read_optimize_tail(log_path, keep='first')
    first_rms = float(first['Cell Stress RMS']) if 'Cell Stress RMS' in first \
        else None
    limit_rms = float(params.get('opt_csrms') or DEFAULT_OPT_CSRMS)
    limit_max = float(params.get('opt_csmax') or DEFAULT_OPT_CSMAX)
    drift = abs(float(volume_last) - float(volume_first))
    reference, reference_drift = _natural_motion_of_the_same_box(
        run_dir, params, volume_first,
        (spec.get('control') or {}).get('theory'))
    result['cell_metrics'].update({
        'pressure_target_bar': pressure,
        'pressure_residual_rms_bar': rms,
        'pressure_residual_max_bar': maximum,
        'pressure_converged': bool(tail.get('Converged', False)),
        'volume_drift_under_load': drift,
        'pressure_reference_example': reference or 'none',
        'pressure_reference_drift': (float(reference_drift)
                                     if reference_drift is not None else None),
    })
    if first_rms is not None:
        result['cell_metrics']['pressure_residual_first_bar'] = first_rms
    problems = []
    if abs(stated - pressure) > 1.0e-6:
        problems.append(
            'the run declares opt_pressure %.6f bar and the optimizer reports '
            'External Pressure %.6f bar: the keyword did not reach the search, '
            'so this box was relaxed against %s'
            % (pressure, stated, 'no applied pressure'
               if not stated else 'a different pressure'))
    if (first_rms is not None and rms >= first_rms
            and result['cell_metrics'].get('steps', 0) > 1):
        # One block is not a direction: there is nothing to come down from. Two
        # recorded steps or more and an endpoint no better than the first is.
        problems.append(
            'the load drove the box away from its rest point: the residual of '
            '`sigma + p I` was %.1f bar at its first recorded step and %.1f bar '
            'at its last, so a threshold on the endpoint alone would never have '
            'seen the direction' % (first_rms, rms))
    if reference is None:
        paired = ('paired against nothing: the round holds no zero-pressure leg '
                  'of this box, engines, optimizer and coupling to compare the '
                  'direction with')
    elif reference == 'ambiguous':
        paired = ('paired against nothing: %d zero-pressure twins of this box are '
                  'on the plan and choosing one is not a measurement'
                  % reference_drift)
    else:
        paired = ('paired against %s, which drifted %.6f A^3 unloaded: this leg '
                  'drifted %.6f A^3 under %.1f bar'
                  % (reference, reference_drift, drift, pressure))
        if drift >= reference_drift:
            problems.append(
                'the applied pressure failed to oppose the box\'s own motion: %s '
                'drifted %.6f A^3 with no load on it while this leg drifted '
                '%.6f A^3 under %.1f bar. That is the sign error an endpoint '
                'residual cannot show, because a box that starts more compressed '
                'than the load rests at a larger volume, not a smaller one'
                % (reference, reference_drift, drift, pressure))
    # The band and the convergence flag: read, printed, and NOT judged. Ruled on
    # 2026-10-19 on round `tmp_20261019_122659`'s own numbers - these legs run at
    # `maxit: 5`, a functional-test budget, and that round's isotropic leg walked
    # 10818.1 -> 9732.0 -> 6971.1 -> 181.5 -> 1319.9 bar, crossing its rest point
    # at 1168.87 A^3 on step 4 and rebounding, so the endpoint the criteria were
    # judging was the rebound of a run that had already arrived. What a five-step
    # box says nothing about is whether the band is reachable; what it does say,
    # and what stays judged above, is that the load moved the box the way a load
    # moves it. The reading is printed with its thresholds either way, because a
    # number withheld from the document is a number nobody can re-check.
    notes = []
    if rms > limit_rms:
        notes.append('the endpoint still carries %.1f bar of residual '
                     '`sigma + p I` against opt_csrms %.1f bar'
                     % (rms, limit_rms))
    if maximum > limit_max:
        notes.append('the endpoint still carries %.1f bar on its largest '
                     'lattice component against opt_csmax %.1f bar'
                     % (maximum, limit_max))
    if not tail.get('Converged', False):
        notes.append('the run reports Converged: False at its last recorded '
                     'step, so the box stopped short of its target pressure')
    if problems and result.get('status') == 'pass':
        result['status'] = 'fail'
    result['details'] = ((result.get('details') or '') +
        '\n[CELL] pressure %.1f bar: endpoint residual sigma + p I = %.1f bar '
        '(rms) / %.1f bar (max) against %.1f / %.1f bar, Converged: %s; %s%s%s'
        % (pressure, rms, maximum, limit_rms, limit_max,
           'True' if tail.get('Converged', False) else 'False', paired,
           ('; FAILED: ' + '; '.join(problems)) if problems else '',
           ('; NOT JUDGED (functional-test budget): ' + '; '.join(notes))
           if notes else ''))

def _slurm_skill_label(task):
    """The skill a test task runs, by the label its theory queue names."""
    theory = task.get('theory') or ''
    if isinstance(theory, (list, tuple)):
        return str(theory[0]).strip().lower() if theory else ''
    return str(theory).strip().split()[0].lower() if str(theory).strip() else ''


def _find_slurm_artifacts(work_dir, exclude_script=None, skill=''):
    """Collect skill slurm submission artifacts under a test directory.

    Walks the test directory recursively because the skill backend
    writes the sbatch script and the slurm output into its own
    calculation directory. Harness-generated .sbatch scripts (the
    scheduler=slurm entry scripts) are excluded so they cannot mask a
    missing skill artifact.

    Parameters
    ----------
    work_dir : str
        Test working directory to scan.
    exclude_script : str, optional
        Absolute path of the harness-generated sbatch script to
        ignore.
    skill : str, optional
        Skill label whose declared artifact names are matched; the
        historical suffixes apply when it declares none.

    Returns
    -------
    tuple(list, list)
        Paths of skill .sbatch scripts and *_slurm.out files.
    """
    sbatch_files = []
    out_files = []
    from pyrai3md.skills.query import manifest_value

    declared = manifest_value(skill, 'slurm_artifacts', {}) or {}
    script_suffix = str(declared.get('script') or '.sbatch')
    log_suffix = str(declared.get('log') or '_slurm.out')
    exclude = os.path.abspath(exclude_script) if exclude_script else None
    if not os.path.isdir(work_dir):
        return sbatch_files, out_files

    for root, _dirs, files in os.walk(work_dir):
        for fname in files:
            path = os.path.join(root, fname)
            if exclude and os.path.abspath(path) == exclude:
                continue
            if fname.endswith(script_suffix):
                sbatch_files.append(path)
            elif fname.endswith(log_suffix):
                out_files.append(path)

    return sbatch_files, out_files


def _write_results(results, work_dir):
    """Write test results to JSON files.

    Parameters
    ----------
    results : dict
        Test results.
    work_dir : str
        Working directory for output files.
    """
    os.makedirs(work_dir, exist_ok=True)

    results_path = os.path.join(work_dir, 'results.json')
    with open(results_path, 'w', encoding='utf-8') as f:
        json.dump(results, f, indent=2, ensure_ascii=False)

    status_path = os.path.join(work_dir, 'status.json')
    status = {
        'status': results.get('status', 'unknown'),
        'timestamp': results.get('timestamp', ''),
    }
    with open(status_path, 'w', encoding='utf-8') as f:
        json.dump(status, f, indent=2)


def _detail_indent(total):
    """The column every detail line starts in, as a string of spaces.

    The counter occupies the left of a result line, so everything printed
    under it has to clear the counter's own width to line up. The width is
    derived from `total` instead of hardcoded, because the counter is
    zero-padded to it: 10 spaces fit '[38/38]' exactly, which is what the
    shipped logs already look like, and a 107-task round widens the column
    by one without anyone editing a literal.

    tools/deploy.py parses '[idx/total]' out of the captured log to decide
    whether a remote run is still advancing, so the padding stays digits.
    """
    return ' ' * (2 + len('[%s/%s]' % (total, total)) + 1)


def _indent_block(text, indent):
    """Put every line of a multi-line detail at the same left edge.

    The post-run checks append their findings with a leading newline, so a
    verbatim print leaves '[PBC]' and the second half of a traceback
    starting at column 0 while their siblings are indented: same data,
    ragged block, and the eye reads the flush-left lines as belonging to
    the task printed before them.
    """
    lines = str(text or '').strip('\n').splitlines()
    return '\n'.join(indent + line for line in lines)


def _clip_to_lines(text, limit, tail=False):
    """Cut a captured stream to `limit` characters on a line boundary.

    The engine streams are stored as slices, and a raw [-500:] starts
    mid-word: tmp_20260929_091941 recorded a failure as 'ce, rotation)' and
    left the reader to guess the sentence. The same number of characters is
    kept; it just begins and ends on whole lines.
    """
    text = str(text or '')
    if not text or len(text) <= limit:
        return text
    if tail:
        kept = text[-limit:]
        # Drop the partial line the character cut landed in.
        return kept.split('\n', 1)[1] if '\n' in kept else kept
    head = text[:limit]
    return head[:head.rfind('\n')] if '\n' in head else head


def _unit_summary(text):
    """The one counted line a unit-test run ends with.

    pytest writes '66 passed in 0.30s', unittest writes 'Ran 16 tests in
    0.002s' and then 'OK'. A passing task needs that statement, not the
    listing of every case that produced it.
    """
    lines = [line.strip() for line in str(text or '').splitlines()
             if line.strip()]
    if not lines:
        return 'no output'
    for index in range(len(lines) - 1, -1, -1):
        line = lines[index]
        if line.startswith('Ran ') and index + 1 < len(lines):
            return '%s %s' % (line, lines[index + 1])
        if re.search(r'\b\d+ (passed|failed|error)', line):
            return line
    return lines[-1]


# A note line is what a post-run check appends to describe the verdict it
# just reached ('[ENERGY CHECK] no case.md.energies under …', '[UNIT] ran=…',
# '[DIAG cell_gate] 3 finding(s) …'). These qualify a PASS -- they say what
# the run did not judge -- so they survive the filter that drops the verbatim
# captured stream. The benchmark payload is excluded because the metric lines
# printed under it carry the same numbers.
_NOTE_TAG = re.compile(r'^\[(?!BENCHMARK)[A-Z][A-Za-z0-9_ ]*\]')


def _verdict_notes(details):
    """The note lines a task appended to its own details."""
    return [line for line in str(details or '').splitlines()
            if _NOTE_TAG.match(line.strip())]


def _print_single_result(result, idx, total):
    """Print a single test result immediately.

    Parameters
    ----------
    result : dict
        Test result dictionary.
    idx : int
        Current test index (1-based).
    total : int
        Total number of tests.
    """
    status = result.get('status', 'unknown').upper()
    name = result.get('name', 'unknown')
    mode = result.get('mode', '')
    theory = result.get('theory', '')
    marker = {
        'PASS': ' + ',
        'FAIL': ' - ',
        'ERROR': ' ! ',
        'SKIP': ' ~ ',
    }.get(status, ' ? ')

    # Theory is only present for example qualification tasks, so the
    # extra bracket is appended conditionally to keep other test
    # output unchanged.
    theory_tag = f'[{theory}]' if theory else ''
    # The counter is zero-padded to the width of the total, which is what
    # makes the column stable enough for the detail lines to align to
    # (and what keeps tools/deploy.py's r'\[(\d+)/(\d+)\]' matching).
    indent = _detail_indent(total)
    counter = '[%0*d/%d]' % (len(str(total)), idx, total)
    line = (f'  {counter} {marker}{name} '
            f'[{mode}]{theory_tag} -> {status}')
    print(line, flush=True)

    # What a block shows depends on its verdict, not on who produced it.
    # A failure shows the captured stream (clipped on a line boundary and
    # re-indented whole: '[NPT STABILITY]' and '[PBC]' are separate findings,
    # not continuation text). A pass shows only the note lines the post-run
    # checks appended -- '[UNIT] ran=…' counts what passed, and '[ENERGY
    # CHECK] no …' says this verdict was reached without the records it
    # wanted, which is exactly the qualification a silent green used to hide.
    # The verbatim engine tail a passing task keeps in `details` stays in
    # results.json, where a reader can reach it, instead of 500 lines of it
    # landing between two task verdicts.
    details = result.get('details', '')
    if status == 'PASS':
        block = '\n'.join(_verdict_notes(details))
    elif result.get('closed_reasons'):
        # The live stream carries the size of the fold, one line; the list of
        # keys it stands for belongs to the report, where a reader looks for
        # "which switch do I edit". Printing 72 `disabled by examples.* x1`
        # tokens here would put back the wall of text the fold removed.
        block = ('[FOLD] %d tasks closed by %d switch(es); keys listed in the '
                 'report' % (result.get('skip_count', 1),
                             len(result['closed_reasons'])))
    else:
        block = _clip_to_lines(details, 200)
    if block:
        print(_indent_block(block, indent), flush=True)
    if status == 'SKIP' and result.get('input_file'):
        print(f'{indent}input: {result["input_file"]}', flush=True)

    # Benchmark results carry a parsed metrics report; print one
    # line per metric so the calibration outcome is visible without
    # opening results.json. Judged differences carry a tolerance
    # and a per-metric verdict; reported quantities (no tolerance
    # entry) print the bare value.
    metrics = result.get('metrics')
    if isinstance(metrics, dict):
        tolerances = metrics.get('tolerances', {}) or {}
        for name, value in (metrics.get('metrics', {}) or {}).items():
            tolerance = tolerances.get(name)
            if tolerance is None:
                print(f'{indent}{name}: {value:g}', flush=True)
            else:
                mark = 'PASS' if value <= tolerance else 'FAIL'
                print(f'{indent}{name}: {value:g} '
                      f'(tolerance {tolerance:g}) -> {mark}',
                      flush=True)
        runtime = metrics.get('runtime_seconds')
        if runtime is not None:
            print(f'{indent}runtime: {runtime} s', flush=True)


def print_report(results):
    """Print a formatted test summary report to console.

    Individual results were already printed during run_tests().
    This prints the final summary and any error/failure tracebacks.

    Parameters
    ----------
    results : dict
        Test results from run_tests().
    """
    all_results = (results.get('main_results', [])
                   + results.get('example_results', [])
                   + results.get('skill_results', [])
                   + results.get('benchmark_results', []))
    total = len(all_results)
    passed = sum(1 for r in all_results if r.get('status') == 'pass')
    failed = sum(1 for r in all_results if r.get('status') == 'fail')
    errors = sum(1 for r in all_results if r.get('status') == 'error')
    # A folded row is worth the tasks it stands for, so the skip total reads
    # their counts; the row count above is what was printed. Both units are
    # named in the summary line, because `Total` alone reads as if Pass +
    # Skip should add up to it.
    skip_rows = sum(1 for r in all_results if r.get('status') == 'skip')
    skipped = sum(r.get('skip_count', 1) for r in all_results
                  if r.get('status') == 'skip')

    # Overall verdict is binary (pass/fail); the skip count is shown
    # as a bracketed suffix, e.g. PASS[SKIP 4].
    overall = results.get('status', 'unknown').upper()
    if skipped:
        overall += f'[SKIP {skipped}]'

    print('\n' + '=' * 60)
    print('  PyRAI3MD Test Report')
    print('=' * 60)
    print(f'  Timestamp: {results.get("timestamp", "N/A")}')
    print(f'  Overall:   {overall}')
    print('-' * 60)

    summary = (f'  Total rows: {total}  Pass: {passed}  Fail: {failed}  '
               f'Error: {errors}')
    if skip_rows:
        summary += f'  Skip rows: {skip_rows} ({skipped} skipped tasks)'
    print(summary)
    print('=' * 60)

    # Print error and failure tracebacks
    for r in all_results:
        name = r.get('name', 'unknown')
        for tb in r.get('error_tracebacks', []):
            print(f'\n  ERROR: {tb.get("test", name)}')
            print(f'  {tb.get("traceback", "").strip()}')
        for tb in r.get('failure_tracebacks', []):
            print(f'\n  FAIL: {tb.get("test", name)}')
            print(f'  {tb.get("traceback", "").strip()}')
        # Print stderr for subprocess failures
        if r.get('status') == 'fail' and r.get('stderr'):
            print(f'\n  FAIL: {name}')
            print(f'  {r["stderr"].strip()[-1000:]}')

    # Print skip reasons, grouped by the reason itself. A closed switch can
    # account for a hundred tasks at once now that the plan lists what it
    # closed, and repeating the same three lines per task buries the one thing
    # the operator came to read: which key to edit. A folded row already
    # carries that answer per key, so it prints as one entry of its own
    # instead of being split back into the reasons it collected.
    folded = [r for r in all_results if r.get('closed_reasons')]
    grouped = {}
    for r in all_results:
        if r.get('status') != 'skip' or r.get('closed_reasons'):
            continue
        reason = r.get('skip_reason') or 'Prerequisites not met'
        grouped.setdefault(reason, []).append(
            (r.get('name', 'unknown'), r.get('input_file')))
    for row in folded:
        count = row.get('skip_count', 1)
        print(f'\n  SKIP x{count}: {row.get("name")} '
              f'({len(row["closed_reasons"])} switches closed)')
        indent = _detail_indent(total)
        print(_indent_block(textwrap.fill(row.get('details', ''), width=76),
                            indent))
    for reason, entries in sorted(grouped.items(),
                                  key=lambda item: (-len(item[1]),
                                                    item[0])):
        print(f'\n  SKIP x{len(entries)}: {reason}')
        if len(entries) <= 3:
            # Few enough that naming each one is the useful reading.
            for name, input_file in entries:
                print(f'    {name}')
                if input_file:
                    print(f'      Input:  {input_file}')
        else:
            names = ', '.join(name for name, _file in entries)
            print(f'    {names}')

    print()


def cli_entry():
    """Entry point for `pyrai3md test` command.

    Loads pmd_env.yaml, generates plan, runs all tests,
    and prints the report.
    """
    from .manager import load_config, generate_plan, create_work_dir
    from ..kernel.environment import ensure_user_config

    ensure_user_config()
    config = load_config()
    # Planning writes the generated inputs and the per-group directories;
    # on a large round it is the first thing that takes time, so say so
    # before the wait: the deploy poller reads this log and a silent start
    # is indistinguishable from a hung one.
    print('  Planning the test round...', flush=True)
    work_dir = create_work_dir()
    plan = generate_plan(config, work_dir)
    planned = sum(len(plan.get(key, []) or []) for key in
                  ('main_tests', 'example_tests', 'skill_tests',
                   'benchmark_tests'))
    print('  Plan ready: %d planned tasks, work directory %s'
          % (planned, work_dir), flush=True)
    results = run_tests(plan, config)
    print_report(results)

    return results
