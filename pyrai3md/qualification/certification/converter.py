def _append_md_echo_pairs(config, pairs):
    """Append the dynamics/ensemble keywords present in the config.

    Presence-based echo: the flat config only carries the keys the
    source YAML actually wrote (yaml_to_config copies them verbatim),
    so presence is the user-provenance record -- a keyword equal to
    the framework default (nactype ktdc, initcond 0, ...) is echoed
    too, keeping the classic input and the agent config complete and
    the three modes identical. Without the echo the input/agent modes
    silently fall back to the framework defaults (sfhp 'nosh',
    ensemble 'nve', ...) and would no longer run the same dynamics as
    the direct-YAML mode.

    Parameters
    ----------
    config : dict
        Flat agent JSON config.
    pairs : list of tuple
        (key, value) pairs to extend in place.

    Returns
    -------
    list of tuple
        The extended pairs list.
    """
    for key, label in _MD_ECHO_KEYS:
        value = config.get(key)
        if value is None and key == 'temperature':
            value = config.get('temp')
        if value is None:
            continue
        pairs.append((label, value))
    return pairs


def _constraint_block(config):
    """The constraint declaration of a test config, wherever it is written.

    An example YAML carries it under `system` (the submodel it belongs to) and a
    flat dev_tool JSON can carry it at the top level; both are the same mapping
    and the classic section name is `constraint` either way.
    """
    system = config.get('system')
    block = config.get('constraints')
    if not block and isinstance(system, dict):
        block = system.get('constraints')
    return block or {}


