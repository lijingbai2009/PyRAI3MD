def _read_control(control, basename):
    """Flatten &CONTROL into the flat keys both carriers consume.

    Adding a control keyword means adding a row to `_CONTROL_FIELDS`
    rather than another `if` in `yaml_to_config`; the row states the
    classic alias the parser also accepts, the transform, whether the
    pair is written and the default it falls back to.

    Parameters
    ----------
    control : dict
        The parsed `control` section (a non-dict is treated as empty).
    basename : str
        YAML file stem, the title's default.

    Returns
    -------
    dict
        Flat config keys in the order the rows declare them.
    """
    if not isinstance(control, dict):
        control = {}

    flat = {}
    for key, alias, transform, emission, default in _CONTROL_FIELDS:
        if default is _TITLE_FROM_FILE:
            default = basename
        raw = control.get(key, control.get(alias, default) if alias else default)
        if emission == _PRESENT and key not in control and (
                alias is None or alias not in control):
            continue
        if emission == _TRUTHY and not raw:
            continue
        value = transform(raw) if transform is not None else raw
        if emission == _NONEMPTY and not value:
            continue
        flat[key] = value
    return flat


# Molecule/md keywords that carry a center axis in multi-center input
# (dev/MULTICENTER_DEVELOPMENT.md section 4). Their classic string
# form uses ';' to split centers; a nested list is the per-center
# structured form.
_CENTER_FIELDS = ('highlevel', 'midlevel', 'ci', 'spin', 'coupling',
                  'root', 'charges', 'multiplicity')


def _is_multicenter(config):
    """Detect a multi-center configuration from its center fields.

    A center field is multi-center when it is a classic string carrying
    the ';' center separator, or a nested list whose depth exceeds the
    single-center form of that field:

    - highlevel/midlevel/ci/spin: single center is a flat list, multi
      center is list[center] (first element is a list).
    - coupling: single center is already list[pair] (first element is a
      pair), multi center is list[center][pair] (first element's first
      element is a pair).
    - root/charges/multiplicity: single center is a scalar, multi center
      is list[center].

    Scalar/flat single-center values return False, so the single-center
    builder path stays untouched.

    Parameters
    ----------
    config : dict
        Flat skill config.

    Returns
    -------
    bool
        True when any center field carries more than one center.
    """
    for key in _CENTER_FIELDS:
        value = config.get(key)
        if value is None:
            continue
        if isinstance(value, str):
            if ';' in value:
                return True
            continue
        if not isinstance(value, (list, tuple)) or not value:
            continue
        first = value[0]
        if key == 'coupling':
            # list[center][pair]: the first pair's first element is a
            # list only in the per-center form.
            if (isinstance(first, (list, tuple)) and first
                    and isinstance(first[0], (list, tuple))):
                return True
        elif key in ('root', 'charges', 'multiplicity'):
            # A list is always per-center (single center is scalar).
            return True
        else:
            # highlevel/midlevel/ci/spin: list[center] has a list first.
            if isinstance(first, (list, tuple)):
                return True
    return False


def _render_center_string(value):
    """Normalize a center-dimensioned value to the classic ';' string.

    A classic string is passed through verbatim (external 1-based for
    highlevel/coupling and root alike, per the adapter contract).
    A nested list is joined into the ';'-separated center form: each
    center is space-joined, and a center that is itself a list of
    pairs (coupling) joins its pairs with ', '. Nested-list values are
    taken as the external 1-based form as written in the source YAML.

    Parameters
    ----------
    value : str or list
        Center field value from the flat config.

    Returns
    -------
    str
        Classic ';'-separated center string.
    """
    if isinstance(value, str):
        return value.strip()
    if not isinstance(value, (list, tuple)):
        return str(value)
    groups = []
    for item in value:
        if isinstance(item, (list, tuple)):
            if item and isinstance(item[0], (list, tuple)):
                # List of pairs (coupling): 'i j, k l'
                groups.append(', '.join(
                    ' '.join(str(x) for x in pair) for pair in item))
            else:
                groups.append(' '.join(str(x) for x in item))
        else:
            groups.append(str(item))
    return '; '.join(groups)


def _needs_md_section(config):
    """Whether a non-advanced jobtype still needs an &MD section.

    A multi-center single-shot job (e.g. jobtype 'gradient') carries
    its per-center initial state in md.root, which the framework only
    reads from the &MD section. The section is emitted whenever a
    multi-center config carries root, even though the jobtype is not an
    advanced (md/optimize/...) workflow; the workflow itself is still
    resolved from jobtype, so the extra &MD section never turns a
    single-shot job into dynamics.

    Parameters
    ----------
    config : dict
        Flat skill config.

    Returns
    -------
    bool
        True when an &MD section must be rendered.
    """
    return _is_multicenter(config) and config.get('root') is not None


def load_config(config_path):
    """Load a flat .json config file.

    Older sectioned configs (system/properties/dynamics/calculation/
    environment nesting) are normalized to the flat layout so all
    conversion entry points consume one contract.

    Parameters
    ----------
    config_path : str
        Path to the .json config file.

    Returns
    -------
    dict
        Parsed configuration dictionary.
    """
    with open(config_path, 'r', encoding='utf-8') as f:
        config = json.load(f)

    return _flatten_legacy_sections(config)


# Submodel sections used by the legacy sectioned skill config format.
_LEGACY_SECTIONS = ('system', 'properties', 'dynamics',
                    'calculation', 'environment')


def _flatten_legacy_sections(config):
    """Flatten a legacy sectioned config into the flat layout.

    Pre-#141 skill configs nest every keyword inside the skill
    submodel sections; the flat builders read them at the top
    level. Nested section keys are lifted to the top level without
    overriding keys already present there (flat configs pass
    through unchanged).

    Parameters
    ----------
    config : dict
        Parsed configuration dictionary.

    Returns
    -------
    dict
        Flat configuration dictionary.
    """
    if not isinstance(config, dict):
        return config

    flat = dict(config)
    for section_name in _LEGACY_SECTIONS:
        section = config.get(section_name)
        if not isinstance(section, dict):
            continue
        for key, value in section.items():
            if key not in flat:
                flat[key] = value

    return flat


def _render_grid_value(grid, section_name='search'):
    """Render one scan grid as the classic `;`-separated keyword groups.

    The reader of this text is `schema.adapter._parse_search_grid`, which
    accepts the same mapping from the yaml carrier and the same groups
    written on separate `grid` lines, so the three carriers agree on what
    the grid is. A candidate that is not a scalar has no text spelling
    here: ';' already separates the keywords of the grid, so a candidate
    that is itself a list would be read back as something else. It is
    refused at conversion rather than rendered wrongly or dropped.
    """
    if not isinstance(grid, dict) or not grid:
        raise ValueError(
            "%s.grid must map a keyword to its candidate list; got %r"
            % (section_name, grid))
    groups = []
    for keyword in sorted(grid):
        candidates = grid[keyword]
        if not isinstance(candidates, (list, tuple)):
            candidates = [candidates]
        if not candidates:
            raise ValueError(
                "%s.grid keyword %r carries no candidate value"
                % (section_name, keyword))
        tokens = []
        for candidate in candidates:
            if isinstance(candidate, (list, tuple, dict)):
                raise ValueError(
                    "%s.grid keyword %r carries a candidate that is itself "
                    "a collection (%r); the classic text separates grid "
                    "keywords with ';', so a list-valued keyword has no "
                    "text spelling -- declare the grid in a yaml input"
                    % (section_name, keyword, candidate))
            tokens.append('false' if candidate is False else
                          'true' if candidate is True else str(candidate))
        groups.append(' '.join([str(keyword)] + tokens))
    return '; '.join(groups)


def _build_workflow_section_pairs(name, config):
    """Collect the pairs of one framework workflow section.

    Parameters
    ----------
    name : str
        Section name ('search', 'train', 'prediction', 'hessian').
    config : dict
        Flat config carrying the section as a dict under its own name.

    Returns
    -------
    list of tuple
        Ordered (key, value) pairs; empty when the config carries no
        such section.

    Raises
    ------
    ValueError
        If the section names a keyword the node has no field for: a
        keyword that no carrier would read back is a conversion error,
        not something to drop.
    """
    section = config.get(name)
    if not isinstance(section, dict) or not section:
        return []
    known = WORKFLOW_SECTION_KEYS[name]
    unknown = sorted(set(section) - set(known))
    if unknown:
        raise ValueError(
            "&%s carries keyword(s) %s the node has no field for; known: %s"
            % (name.upper(), ', '.join(unknown), ', '.join(known)))
    return [(key, section[key]) for key in known if key in section]


def _build_slurm_pairs(config):
    """Collect the Slurm allocation the run asks the cluster for.

    The section is the framework's, keyed by the directive names
    `kernel.sbatch.SBATCH_OPTIONS` understands. Sorted key order keeps
    the generated text stable between runs, and a value is stated the way the
    classic reader will hand it back: booleans as `true`/`false`, which
    `Environment.apply_slurm_overrides` converts back for the one flag
    directive.
    """
    section = config.get('slurm')
    if not isinstance(section, dict) or not section:
        return []
    pairs = []
    for key in sorted(section):
        value = section[key]
        if isinstance(value, bool):
            value = 'true' if value else 'false'
        pairs.append((key, value))
    return pairs


def _build_slurm_section(config):
    """Render the &SLURM section, or nothing when the run says none."""
    pairs = _build_slurm_pairs(config)
    if not pairs:
        return ''
    return _render_section('SLURM', pairs, separator=' ')


def _build_workflow_sections(config):
    """Render every framework workflow section the config declares."""
    blocks = []
    for name in WORKFLOW_SECTION_ORDER:
        pairs = _build_workflow_section_pairs(name, config)
        if not pairs:
            continue
        rendered = [(key, _render_grid_value(value, name)
                     if key == 'grid' else value) for key, value in pairs]
        blocks.append(_render_section(name.upper(), rendered, separator=' '))
    return blocks


def _needs_default_md_section(config, jobtype):
    """Whether a classic input for this job still needs an &MD section.

    A dynamics-driven jobtype asks the skill for per-step properties, so
    its parameters have to be stated. The machine-learning jobtypes do
    not: they own a section of their own and propagate nothing, and a
    default &MD would be parsed as a dynamics request no one made.
    """
    if jobtype in _SECTIONED_ADVANCED_JOBTYPES:
        return False
    return True


