# config (.config). They mirror what the classic input pipeline
# resolves from the coordinate/velocity files so agent mode consumes
# identical data; the state keywords (nstate/state_spin/charges/
# multiplicity) are appended by _build_molecule_pairs.
_STRUCTURE_KEYS = ('atoms', 'coordinates', 'velocities')


def _derive_agent_ci_spin(molecule):
    """Derive legacy ci/spin lists into an agent-mode molecule dict.

    Agent-mode counterpart of the ci/spin derivation the classic text
    renderer performs in _render_molecule_section. Counts the states per
    2S in state_spin (list of 2S per state) and lists the blocks in
    ascending 2S order (spin = 2S // 2), the order the molcas skill
    runs the ladder in; falls back to nstate + multiplicity when
    state_spin is absent. Mutates molecule in place; a no-op when
    neither state_spin nor a positive int nstate exists.

    Parameters
    ----------
    molecule : dict
        Agent-mode molecule section (nstate/state_spin/multiplicity).
    """
    state_spin = molecule.get('state_spin')
    if state_spin:
        ci_roots, spins = _group_state_spin(state_spin)
        molecule['ci'] = ci_roots
        molecule['spin'] = [s // 2 for s in spins]
        return
    nstate = molecule.get('nstate')
    if isinstance(nstate, int) and nstate >= 1:
        multiplicity = int(molecule.get('multiplicity', 1))
        molecule['ci'] = [nstate]
        molecule['spin'] = [(multiplicity - 1) // 2]


def _build_sectioned_dict(config, task_name, skill_name):
    """Assemble the shared sectioned dict for one test case.

    The dict is the single source for both output formats: the
    classic input text (section builders) and the pyrai3md config
    JSON (convert_to_pyrai_config). Section names match the classic
    parser output ('control'/'molecule'/'md'/'optimize'), and the
    skill section is keyed by the full skill name (e.g. 'xtb_skill')
    so multi-backend agent configs stay distinguishable per skill.

    Parameters
    ----------
    config : dict
        Flat skill config (dev_tool / yaml_to_config output).
    task_name : str
        Task name used as the control title.
    skill_name : str
        Skill identifier (e.g. 'molcas_skill').

    Returns
    -------
    dict
        Sectioned configuration dictionary.
    """
    jobtype = _resolve_jobtype(config)
    advanced_jobtypes = ('md', 'adaptive', 'optimize', 'train',
                         'prediction', 'search', 'surface_hopping')
    is_advanced = jobtype in advanced_jobtypes

    sectioned = {}

    # Framework sections
    _name, pairs = _build_control_pairs(config, task_name, skill_name)
    sectioned['control'] = dict(pairs)

    # Molecule section: structure data (agent-mode equivalent of the
    # coordinate/velocity files the classic parser resolves) followed
    # by the state keywords; all are System submodel fields.
    _name, pairs = _build_molecule_pairs(config)
    molecule = {}
    for key in _STRUCTURE_KEYS:
        value = config.get(key)
        if value is None:
            continue
        if isinstance(value, (list, tuple)) and not value:
            continue
        molecule[key] = value
    molecule.update(dict(pairs))
    # Agent-mode ci/spin derivation: the classic text renderer derives
    # the legacy ci/spin keywords from nstate/state_spin at render time
    # (_render_molecule_section), but the agent dict is consumed
    # directly, so without this the framework defaults ci=[1] and
    # validate_centers rejects a multistate coupling pair (state 1 out
    # of range 0..0). Mirror the renderer's grouping so pyrai3md_agent
    # carries the same effective electronic structure as pyrai3md input
    # mode (convert_to_pyrai_config contract). Single-center only; a
    # multicenter config already emits ci verbatim in _build_molecule_
    # pairs, and an explicit ci always wins.
    if 'ci' not in molecule and not _is_multicenter(config):
        _derive_agent_ci_spin(molecule)
    sectioned['molecule'] = molecule

    _name, pairs = _build_constraint_pairs(config)
    if pairs:
        # Keyed by the classic section name, which `schema.adapter` routes to
        # `system.constraints`; the agent config therefore carries the same
        # declaration as the classic text does.
        sectioned['constraint'] = dict(pairs)

    if jobtype == 'optimize':
        _name, pairs = _build_optimize_pairs(config)
        sectioned['optimize'] = dict(pairs)
    elif (is_advanced or _needs_md_section(config)) and _needs_default_md_section(
            config, jobtype):
        _name, pairs = _build_md_pairs(config)
        sectioned['md'] = dict(pairs)
        if jobtype == 'adaptive':
            pairs = _build_adaptive_pairs(config)
            if pairs:
                sectioned['adaptive'] = dict(pairs)

    # Framework workflow sections, nested under their own names: the agent
    # config keeps `grid` as the mapping the yaml carrier has, while the
    # classic text carries the same groups as one ';'-separated line. Both
    # are read back by `schema.adapter._parse_search_grid`, so the two
    # spellings mean one plan.
    for name in WORKFLOW_SECTION_ORDER:
        pairs = _build_workflow_section_pairs(name, config)
        if pairs:
            sectioned[name] = dict(pairs)

    slurm_pairs = _build_slurm_pairs(config)
    if slurm_pairs:
        sectioned['slurm'] = dict(slurm_pairs)

    # Skill section(s) keyed by the full skill name; a multi-theory
    # composite (multi-center ONIOM) emits one section per skill from
    # the preserved 'skill_sections', so the high and low level keep
    # their own method/basis instead of colliding. The skill-specific
    # pair builder is imported lazily so this generic module never
    # loads the skill layer at import time.
    from .handler import _build_skill_pairs, _skill_subsection_values
    skill_sections = config.get('skill_sections') or {}
    if skill_sections:
        for stem, params in skill_sections.items():
            full_name = _skill_folder(stem)
            _name, pairs = _build_skill_pairs(config, full_name, params)
            sectioned[full_name] = dict(pairs)
            for sub, values in _skill_subsection_values(
                    config, full_name, params):
                sectioned[sub] = values
    else:
        _name, pairs = _build_skill_pairs(config, skill_name)
        sectioned[skill_name] = dict(pairs)
        for sub, values in _skill_subsection_values(config, skill_name):
            sectioned[sub] = values

    return sectioned


def convert(config_path, output_path=None, skill_name=None):
    """Convert a flat .json config to PyRAI2MD classic .input text.

    Generates sections based on skill_name and jobtype:
    - Always: &CONTROL + method block + &MOLECULE
    - Advanced jobtypes (md, adaptive, optimize, etc.): also &MD

    The skill_name is resolved in priority order:
    1. 'skill_name' field in the JSON config
    2. The skill_name parameter
    3. Default: 'molcas_skill'

    Parameters
    ----------
    config_path : str
        Path to the input .json file.
    output_path : str, optional
        Path for the output .input file. If None, returns
        the text content without writing.
    skill_name : str, optional
        Skill identifier (e.g. 'molcas_skill'). Determines the method block.
        Overridden by 'skill_name' in the JSON config.

    Returns
    -------
    str
        Classic input text content.
    """
    config = load_config(config_path)

    # Resolve skill_name: JSON config > parameter > default
    effective_skill = _named_skill(config, skill_name)

    # Derive task name: title is the single naming source (yaml
    # name for skill tests, control title for examples); fall back
    # to the config file stem.
    basename = os.path.splitext(os.path.basename(config_path))[0]
    task_name = str(config.get('title') or basename)

    # Determine if advanced jobtype needs extra sections
    jobtype = _resolve_jobtype(config)
    advanced_jobtypes = ('md', 'adaptive', 'optimize', 'train', 'prediction', 'search', 'surface_hopping')
    is_advanced = jobtype in advanced_jobtypes

    # Build sections: always include control, method, molecule; a
    # multi-theory composite (multi-center ONIOM) renders one method
    # section per preserved skill so the high and low level keep their
    # own keywords. The skill-specific method section builder is
    # imported lazily so this generic module never loads the skill
    # layer at import time.
    from .handler import _build_method_section, build_subsection_blocks
    skill_sections = config.get('skill_sections') or {}
    if skill_sections:
        method_sections = [
            _build_method_section(config, _skill_folder(stem), params)
            for stem, params in skill_sections.items()
        ]
        subsection_blocks = [
            block
            for stem, params in skill_sections.items()
            for block in build_subsection_blocks(
                config, _skill_folder(stem), params)
        ]
    else:
        method_sections = [_build_method_section(config, effective_skill)]
        subsection_blocks = build_subsection_blocks(config, effective_skill)
    sections = (
        [_build_control_section(config, task_name, effective_skill)]
        + method_sections
        + subsection_blocks
        + [_build_molecule_section(config)]
    )

    # Add jobtype-specific sections
    if jobtype == 'optimize':
        sections.append(_build_optimize_section(config))
    elif (is_advanced or _needs_md_section(config)) and _needs_default_md_section(
            config, jobtype):
        sections.append(_build_md_section(config))
        if jobtype == 'adaptive':
            adaptive_section = _build_adaptive_section(config)
            if adaptive_section:
                sections.append(adaptive_section)
    sections.extend(_build_workflow_sections(config))
    slurm_section = _build_slurm_section(config)
    if slurm_section:
        sections.append(slurm_section)

    # The constraint block after the workflow sections: it is not a skill's
    # parameters and not a dynamics setting, and reading it needs the atoms the
    # molecule section above already resolved.
    constraint_section = _build_constraint_section(config)
    if constraint_section:
        sections.append(constraint_section)

    content = '\n\n'.join(sections) + '\n'

    if output_path:
        with open(output_path, 'w', encoding='utf-8') as f:
            f.write(content)

        # Write same-basename .xyz file for pyrai3md_input mode
        _write_xyz_file(config, output_path)
        _write_velocity_file(config, output_path)

    return content


def convert_to_pyrai_config(config_path, output_path=None, skill_name=None):
    """Convert a flat .json config to a pyrai3md .config JSON file.

    The sectioned dict assembled here shares every builder with the
    classic input rendering (convert), so pyrai3md_agent consumes
    exactly the same effective configuration as pyrai3md input mode.
    Structure and state fields live in the molecule section (System
    submodel fields); skill parameters live in the full-skill-name
    section (e.g. 'xtb_skill').

    Parameters
    ----------
    config_path : str
        Path to the input .json file.
    output_path : str, optional
        Path for the output .config file. If None, the sectioned
        dict is only returned without writing.
    skill_name : str, optional
        Skill identifier (e.g. 'molcas_skill'). Overridden by
        'skill_name' in the JSON config.

    Returns
    -------
    dict
        Sectioned configuration dictionary.
    """
    config = load_config(config_path)

    effective_skill = _named_skill(config, skill_name)

    basename = os.path.splitext(os.path.basename(config_path))[0]
    task_name = str(config.get('title') or basename)

    sectioned = _build_sectioned_dict(config, task_name, effective_skill)

    if output_path:
        with open(output_path, 'w', encoding='utf-8') as f:
            json.dump(sectioned, f, indent=2, ensure_ascii=False)

    return sectioned


