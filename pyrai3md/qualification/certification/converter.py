def parse_test_yaml(yaml_path, skill_name):
    """Parse one skill test YAML into a flat skill config dict.

    Unified replacement of the former per-skill dev_tool.generate:
    copies every key of the YAML 'input' section and injects the
    skill metadata (skill_name, skill_path, theory) through the
    skill's public query interface. The individualized parsing of
    every skill lives here (called by the handler/planner chain):
    all skill-specific keys (project name, coupling defaults,
    current_state routing) follow generic rules keyed by the skill
    identity, so no per-skill branch is needed.

    Parameters
    ----------
    yaml_path : str
        Path to the test YAML file.
    skill_name : str
        Skill identifier (e.g. 'molcas_skill').

    Returns
    -------
    dict
        Flat skill JSON config dictionary.
    """
    with open(yaml_path, 'r', encoding='utf-8') as f:
        test_case = yaml.safe_load(f) or {}
    input_section = test_case.get('input', {})

    config = dict(input_section)

    # The yaml top-level name is the single naming source for the
    # generated task (classic input title / skill project); fall
    # back to the yaml file stem when absent.
    config['title'] = test_case.get('name') or os.path.splitext(
        os.path.basename(yaml_path))[0]

    # Same rule as the classic-input path: the couplings a case declares
    # through the internal pair maps are rendered into `coupling`, and a
    # case that declares no pair on either side gets none. Adjacent pairs
    # used to be injected for every multistate case here, so a skill test
    # printed NAC labels for couplings its input never asked for.
    if not config.get('coupling'):
        _pairs = pairs_to_coupling(config.get('nac_pair_map'),
                                   config.get('soc_pair_map'))
        if _pairs:
            config['coupling'] = _pairs

    # current_state belongs to the system submodel: nest it so the
    # skill and framework config builders route it into
    # config.system.current_state.
    if 'current_state' in config:
        system_section = config.setdefault('system', {})
        system_section['current_state'] = config.pop('current_state')

    # Skill metadata through the public query interface (the sole
    # source of truth for the skill identity).
    query = importlib.import_module(skill_module_path(skill_name))
    meta = query.get_metadata()
    config['skill_name'] = skill_name
    config['skill_path'] = meta['skill_path']
    config['theory'] = [meta['name']]

    # The project name shares the single naming source with the
    # title so tests sharing one profile still get unique file
    # names. The key follows the classic input section stem
    # ('{stem}_project'), matching _build_skill_pairs.
    stem = skill_stem(skill_name)
    project_key = f'{stem}_project'
    if project_key not in config:
        config[project_key] = config['title']

    return config


def _stage_charge_sidecar(config, output_dir):
    """Materialize an inline background embedding as the project's `.charge`.

    A test YAML may spell the embedding inline, in either representation:

        external_charges:   [[q, x, y, z], ...]    # arbitrary external points
        external_potential: [[V, Fx, Fy, Fz], ...] # one row per QM atom

    and the two are refused together, because one file carries one embedding.
    No carrier runs on inline rows: the switch a single-theory queue reads is
    `read_charge: true`, which resolves '{title}.charge' - the same file the
    classic reader opens, the framework's charge store reads for an ONIOM mid
    shell, and a skill's own `read_charge: true` alias expands to. So the rows
    are written out once, behind the declaration that says what they are
    (`point angstrom external` or `field au`), and every generated artifact
    carries the switch instead of the data. A string value already names a
    file and passes through untouched.
    """
    points = config.get('external_charges')
    field = config.get('external_potential')
    inline_points = isinstance(points, (list, tuple)) and bool(points)
    inline_field = isinstance(field, (list, tuple)) and bool(field)
    if not inline_points and not inline_field:
        return
    if inline_points and inline_field:
        raise ValueError(
            "external_charges and external_potential are both given; a "
            "background embedding is external points or a V/E field, never "
            "both.")

    if inline_points:
        declaration = 'point angstrom external'
        columns = 'q, x, y, z'
        rows = points
        key = 'external_charges'
    else:
        declaration = 'field au'
        columns = 'V, Fx, Fy, Fz'
        rows = field
        key = 'external_potential'

    parsed = []
    for position, row in enumerate(rows, start=1):
        parts = list(row or [])
        try:
            values = [float(value) for value in parts]
        except (TypeError, ValueError):
            raise ValueError(
                "%s row %d must be [%s] numbers; got %r"
                % (key, position, columns, row))
        if len(values) != 4:
            raise ValueError(
                "%s row %d must be [%s]; got %r"
                % (key, position, columns, row))
        parsed.append(values)

    project = _derive_project_name(config)
    title = str(config.get('title') or project)
    lines = [declaration, '# %s for %s' % (key, title)]
    for values in parsed:
        lines.append('%16.10f %16.10f %16.10f %16.10f' % tuple(values))
    with open(os.path.join(output_dir, '%s.charge' % project), 'w',
              encoding='utf-8') as handle:
        handle.write('\n'.join(lines) + '\n')

    config.pop(key)
    config['read_charge'] = True


def generate_test_configs(skill_name, output_dir):
    """Generate flat .json configs for all test cases of one skill.

    Unified replacement of the former per-skill dev_tool.generate_all:
    parses every test YAML discovered by the handler, points
    scratch_path at an isolated output_dir/tmp, writes {profile}.json
    files and copies the test data files (topologies, force fields,
    ...) next to the configs so the launch directory is
    self-contained.

    The handler import is resolved lazily: handler.py imports this
    module at load time, so a top-level reverse import would form a
    cycle.

    Parameters
    ----------
    skill_name : str
        Skill identifier (e.g. 'molcas_skill').
    output_dir : str
        Directory receiving the generated .json configs.

    Returns
    -------
    dict
        Mapping {profile_name: config_path}; empty when the skill
        ships no test YAML files.
    """
    from . import handler

    yaml_paths = handler.list_skill_test_yamls(skill_name)
    if not yaml_paths:
        return {}

    os.makedirs(output_dir, exist_ok=True)
    scratch_dir = os.path.join(output_dir, 'tmp')
    os.makedirs(scratch_dir, exist_ok=True)

    # Test data files (anything that is neither a test case nor a
    # python module) are copied next to the generated configs so the
    # qualification runs find them in the launch directory.
    tests_dir = os.path.dirname(yaml_paths[0])
    for fname in sorted(os.listdir(tests_dir)):
        if fname.endswith(('.yaml', '.py')):
            continue
        src = os.path.join(tests_dir, fname)
        if os.path.isfile(src):
            shutil.copy(src, os.path.join(output_dir, fname))

    # Shared topology / force-field fixtures (e.g. the LAMMPS h2o
    # reference system: '<base>.data' plus the optional
    # '<base>.in.init' / '<base>.in.settings' templates) are also
    # staged under each test's project name, because the skill backend
    # resolves the launch-directory topology as '<project>.data'. The
    # project name follows the same '{stem}_project' key parse_test_yaml
    # writes, so no per-skill branch is needed; a skill shipping no
    # such fixture turns this into a no-op.
    stem = skill_stem(skill_name)
    project_key = f'{stem}_project'
    topology_suffixes = ('.data', '.in.init', '.in.settings')
    topology_fixtures = [
        fname for fname in sorted(os.listdir(tests_dir))
        if fname.endswith(topology_suffixes)
        and os.path.isfile(os.path.join(tests_dir, fname))
    ]

    results = {}
    for yaml_path in yaml_paths:
        profile_name = os.path.splitext(os.path.basename(yaml_path))[0]
        config = parse_test_yaml(yaml_path, skill_name)
        config['scratch_path'] = scratch_dir
        _stage_charge_sidecar(config, output_dir)
        config_path = os.path.join(output_dir, f'{profile_name}.json')
        with open(config_path, 'w', encoding='utf-8') as f:
            json.dump(config, f, indent=2, ensure_ascii=False)
        results[profile_name] = config_path

        # Stage a project-named copy of every shared topology fixture
        # so '<project>.data' (and its companions) sit in the launch
        # directory under the name the backend resolves.
        project = str(config.get(project_key) or config.get('title') or '')
        if project:
            for fname in topology_fixtures:
                suffix = next(
                    (s for s in topology_suffixes if fname.endswith(s)),
                    None)
                if suffix is None:
                    continue
                target = f'{project}{suffix}'
                if target == fname:
                    continue
                destination = os.path.join(output_dir, target)
                if os.path.exists(destination):
                    # A case-specific fixture already staged under this
                    # name (copied verbatim by the loop above) wins; a
                    # shared fixture must not overwrite it. Without this,
                    # a skill with two different topologies would stage
                    # whichever filename sorts last onto both projects.
                    continue
                shutil.copy(os.path.join(tests_dir, fname), destination)

    return results
