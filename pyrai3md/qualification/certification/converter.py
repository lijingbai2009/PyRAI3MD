def _named_skill(config, skill_name):
    """The skill a flat config belongs to, refusing an unnamed one.

    `yaml_to_config` writes `skill_name` into every flat config it
    produces, so an empty answer here means the caller built one by hand;
    guessing a skill (the old default was `molcas_skill`) would render
    another skill's section.
    """
    name = config.get('skill_name') or skill_name
    if not name:
        # A hand-built flat config may name its provider only through the
        # theory queue; that is a statement, not a guess.
        theory = config.get('theory') or []
        first = str(theory[0]).strip() if theory else ''
        name = _skill_folder(first) if first else ''
    if not name:
        raise ValueError(
            'a flat skill config must name its skill: skill_name is '
            'missing, no skill was passed, and theory names none')
    return str(name)


def _skill_folder(stem):
    """Resolve a theory stem to the skill package that serves it.

    The stem is the input spelling ('nn' in control.theory and &NN) and
    the package is the folder it lives in ('nn_pes_skill'). For most
    skills the two coincide; for a skill whose manifest label differs from
    its folder name only the registry knows the pair, and the framework
    routes a calculation through that same registry. A stem the registry
    does not know keeps the historical '<stem>_skill' reading.

    Parameters
    ----------
    stem : str
        Theory stem, e.g. 'nn'.

    Returns
    -------
    str
        Skill package name, e.g. 'nn_pes_skill'; empty for an empty stem.
    """
    if not stem:
        return ''
    try:
        from pyrai3md.skills import query as skill_query
        info = skill_query.resolve_label(stem)
    except Exception:
        info = None
    if info and info.get('skill_name'):
        return info['skill_name']
    return f'{stem}_skill'


def _group_state_spin(state_spin):
    """Per-multiplicity state counts, blocks in ascending 2S order.

    This is the one grouping the harness export uses. The molcas deck
    normalizes a standalone input the same way
    (`molcas_skill/schema/normalize.py::verify_state_spin` sorts the
    ladder, then counts runs), so the harness export and the skill run
    read the same ladder. Counting in first-appearance order instead
    exported `[2, 0]` as `spin 1 0` while the skill ran it as `0 1`.

    A list the framework's ci/spin representation cannot carry -- an
    interleaved ladder such as `[0, 2, 0]`, which expires to blocks
    `[0, 0, 2]` -- is regrouped, not refused here: the molcas skill
    refuses it when the run declares state pairs, and this function
    only answers what the counts and the deck order are.

    Parameters
    ----------
    state_spin : list of int
        2S per state.

    Returns
    -------
    tuple of list
        (ci, spins): state count per multiplicity, and the 2S value of
        each block in ascending order.
    """
    counts = {}
    for two_s in state_spin:
        counts[two_s] = counts.get(two_s, 0) + 1
    spins = sorted(counts)
    return [counts[two_s] for two_s in spins], spins


def yaml_to_config(yaml_path, config_path=None):
    """Convert an example workflow YAML to a flat .json config.

    The YAML is parsed through the official Interface layer entry
    point (interface.parser.parse_input), so coordinates, velocities,
    and section handling follow the exact runtime pipeline. The
    resulting flat agent config carries explicit 'jobtype' and
    'theory' fields so downstream conversion and the agent entry
    point behave identically to a skill-generated config.

    Parameters
    ----------
    yaml_path : str
        Path to the example YAML file.
    config_path : str, optional
        Path for the output .json config file. If None, the config
        is only returned without writing.

    Returns
    -------
    dict
        Flat skill JSON config dictionary.
    """
    from ...interface.parser import parse_input

    raw_config = parse_input(yaml_path)
    basename = os.path.splitext(os.path.basename(yaml_path))[0]

    config = {}

    # --- Control section -> explicit title/jobtype/theory ---
    # The field-by-field mapping (aliases, transforms, when a pair is
    # written, defaults) is the table `_CONTROL_FIELDS` next to
    # `_read_control`; this call site only supplies the file stem the
    # title falls back to.
    config.update(_read_control(raw_config.get('control', {}), basename))
    theory_list = config['theory']

    # --- Optimize section -> optimization method and convergence ---
    optimize = raw_config.get('optimize', {})
    if isinstance(optimize, dict):
        opt_method = optimize.get('method', '')
        if opt_method:
            config['opt_method'] = str(opt_method)
        # Forward optimization control keywords with the 'opt_'
        # prefix so they reach the Optimize submodel through the
        # flat config pipeline.  Unprefixed short names (maxit,
        # state_i, ...) are not in FIELD_TO_SUBMODEL and would be
        # silently dropped by _partition_fields.
        for key, value in optimize.items():
            if key == 'method':
                continue
            # A keyword that already names its own section is not prefixed.
            # `optimize_cell` is the case: prefixing it invents
            # `opt_optimize_cell`, a name no model owns, and the switch then
            # vanishes between this config and the optimizer - the run relaxes
            # its atoms and reports nothing about its box. The runtime
            # flattener reads one set for exactly this; the generator reads
            # the same set, so the two cannot drift.
            if key in OPTIMIZE_PASSTHROUGH_KEYS:
                config[key] = value
                continue
            config_key = key if key.startswith('opt_') else 'opt_' + key
            config[config_key] = value

    # --- Structure (already resolved by the Interface layer) ---
    if raw_config.get('atoms'):
        config['atoms'] = list(raw_config['atoms'])
    if raw_config.get('coordinates'):
        config['coordinates'] = [list(row) for row in raw_config['coordinates']]
    if raw_config.get('velocities'):
        config['velocities'] = [list(row) for row in raw_config['velocities']]

    # --- Molecule section -> flat keywords + derived state info ---
    molecule = raw_config.get('molecule', {})
    if not isinstance(molecule, dict):
        molecule = {}

    for key, value in molecule.items():
        if key in ('coord', 'velo'):
            continue
        config[key] = value

    # A case that declares the couplings only through the internal pair
    # maps still has to reach the engine, and a classic input spells them
    # as `coupling`: fill the authority in from what was declared. Nothing
    # is invented here - a case with no pair on either side renders no
    # coupling (adjacent pairs used to be supplied for every nstate >= 2,
    # which printed NAC labels for pairs nobody asked about).
    if not config.get('coupling'):
        _pairs = pairs_to_coupling(config.get('nac_pair_map'),
                                   config.get('soc_pair_map'))
        if _pairs:
            config['coupling'] = _pairs

    # Derive ci_roots / ci_spin from state_spin (all skills)
    state_spin = config.get('state_spin', [])
    if state_spin:
        ci_roots, spins = _group_state_spin(state_spin)
        config['ci_roots'] = ci_roots
        config['ci_spin'] = [two_s // 2 for two_s in spins]

    # --- MD section -> flat keywords ---
    md_section = raw_config.get('md', {})
    if isinstance(md_section, dict):
        for key, value in md_section.items():
            config[key] = value

    # --- Adaptive and framework workflow sections -> carried nested ---
    # Not flattened: only the dispatch trio is shared with the workflow
    # nodes (the adaptive block is rendered as &ADAPTIVE and the workflow
    # sections as their own blocks), so each block is kept as a dict under
    # its own name and the section builders read it from there.
    for section_name in _CARRIED_SECTIONS:
        section = raw_config.get(section_name)
        if isinstance(section, dict) and section:
            config[section_name] = dict(section)

    # --- Constraint block -> the framework's own section, never a skill ---
    # `system_constraint` (and its classic alias `constraint`) declares the
    # restraints. It is a framework section: read as a skill section it renders
    # as &SYSTEM_CONSTRAINT, which carries the skill-project line and the
    # shared scratch_path, and the constraint reader refuses both. The
    # declaration itself would then be dropped, so the classic mode would run
    # the unconstrained physics while the yaml mode ran the constrained one.
    # The flat keywords go through the reader the input pipeline uses, so the
    # grammar stays in one file and `write_constraint_section` has its own
    # inverse to render.
    from pyrai3md.schema.adapter import (
        CONSTRAINT_SECTION_NAMES, _read_constraint_section)

    for section_name in CONSTRAINT_SECTION_NAMES:
        block = raw_config.get(section_name)
        if isinstance(block, dict) and block:
            config['constraints'] = _read_constraint_section(block)

    # --- Skill sections -> per-skill params + primary skill_name ---
    # Every non-framework dict section is one skill's parameter block.
    # A multi-theory composite (e.g. multi-center ONIOM with a high and
    # a low level) carries several skill sections whose keywords
    # collide when flattened (openqp/xtb both define 'method'), so each
    # section is preserved verbatim under 'skill_sections' keyed by the
    # skill stem, ordered by control.theory when available. The primary
    # skill (first theory entry) additionally keeps its keywords flat so
    # the single-skill builder path stays unchanged.
    skill_sections = {}
    for section_name, section_data in raw_config.items():
        if section_name in _FRAMEWORK_SECTIONS:
            continue
        if section_name in CONSTRAINT_SECTION_NAMES:
            continue
        if not isinstance(section_data, dict):
            continue
        skill_sections[section_name] = dict(section_data)

    if theory_list:
        ordered = {stem: skill_sections[stem]
                   for stem in theory_list if stem in skill_sections}
        for stem, params in skill_sections.items():
            if stem not in ordered:
                ordered[stem] = params
        skill_sections = ordered

    primary_stem = theory_list[0] if theory_list else (
        next(iter(skill_sections), ''))
    if primary_stem and primary_stem in skill_sections:
        for key, value in skill_sections[primary_stem].items():
            # The dispatch trio is the exception to flattening the primary
            # skill's keywords to the top level, and for the same reason the
            # blocks stay separate at all: the flat namespace has one spelling
            # for `multitask` and two owners. `&md` writes it (and `&search`,
            # `&train`, `&prediction` carry it nested), and a skill that owns a
            # strain pool writes the same word. Measured on
            # `optimize_cell_cp2k.yaml`: its top level read `multitask=True`
            # and `multipool=2` while those two lines came out of `&cp2k`, so
            # a renderer that echoes the flat trio - which is what `&MD` has to
            # do - would hand the framework node a pool the input never asked
            # for. The block keeps them; `_merge_one_skill_config` reads them
            # from there (#393), and the classic renderer emits them into
            # `&CP2K`.
            if key in _WORKFLOW_DISPATCH_KEYS:
                continue
            config[key] = value

    skill_name = _skill_folder(primary_stem)
    config['skill_name'] = skill_name
    # A run keeps its per-skill blocks when any of three things holds: more
    # than one skill spelled a block, more than one theory ENTRY bound (the
    # multiscale carriers bind `pyscf` twice - #394), or a block declares a
    # dispatch keyword, which the flat namespace cannot attribute (#395). A
    # plain single-skill job with no pool request still gets no
    # 'skill_sections' key, so its builder path and every existing regression
    # output stay byte-identical.
    # What keeping the block costs this one example is two duplicated lines:
    # the sectioned renderer reads calculation keywords from the block, so
    # `charges` and `multiplicity` leave its '&PYSCF' and stay only in
    # '&MOLECULE' - which is how every already-shipped two-backend example
    # renders (round `tmp_20261019_122659`: `optimize_cell_meci` and
    # `optimize_cell_meci_lammps` carry neither line in '&PYSCF', both carry
    # them in '&MOLECULE', and both legs pass).
    keeps_sections = (
        len(skill_sections) > 1
        or len(theory_list) > 1
        or any(key in section for section in skill_sections.values()
               for key in _WORKFLOW_DISPATCH_KEYS))
    if keeps_sections:
        config['skill_sections'] = skill_sections

    if config_path:
        with open(config_path, 'w', encoding='utf-8') as f:
            json.dump(config, f, indent=2, ensure_ascii=False)

    return config


def _join_tokens(value):
    """Join a string or list value into a single space-separated string.

    Parameters
    ----------
    value : str or list
        Raw keyword value.

    Returns
    -------
    str
        Joined string.
    """
    if isinstance(value, (list, tuple)):
        return ' '.join(str(v) for v in value)
    return str(value).strip()


def _token_list(value):
    """Normalize a string or list value into a list of string tokens.

    Parameters
    ----------
    value : str or list
        Raw keyword value.

    Returns
    -------
    list of str
        Token list.
    """
    if isinstance(value, (list, tuple)):
        return [str(v) for v in value]
    return str(value).split()


def _int_list(value):
    """Convert a string or list value into a list of integers.

    Parameters
    ----------
    value : str, int, or list
        Raw keyword value (e.g. '2 2' or [2, 2]).

    Returns
    -------
    list of int
        Integer list.
    """
    if isinstance(value, (list, tuple)):
        return [int(v) for v in value]
    return [int(token) for token in str(value).split()]


def _as_true(_value):
    """The boolean switch is written as True whatever truthy value it read."""
    return True


