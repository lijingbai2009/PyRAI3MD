def _build_adaptive_pairs(config):
    """Assemble the &ADAPTIVE section as (header, keyword pairs).

    The keys come from the reader's own table
    (``schema.adapter.ADAPTIVE_TYPES``), so the classic carrier states
    exactly the adaptive workflow keywords the YAML carrier declared.
    The dispatch trio is part of that table; stage-specific
    ``md_*``/``reference_*`` keys and ``remote_train`` are ordinary
    adaptive fields.
    """
    section = config.get('adaptive')
    if not isinstance(section, dict) or not section:
        return []
    unknown = sorted(set(section) - set(ADAPTIVE_TYPES))
    if unknown:
        raise ValueError(
            "&ADAPTIVE carries keyword(s) %s the reader has no field for; "
            "known: %s" % (', '.join(unknown), ', '.join(ADAPTIVE_TYPES)))
    return [(key, section[key]) for key in ADAPTIVE_TYPES if key in section]


def _build_adaptive_section(config):
    """Render the &ADAPTIVE section, or nothing when none is declared."""
    pairs = _build_adaptive_pairs(config)
    if not pairs:
        return ''
    return _render_section('ADAPTIVE', pairs, separator=' ')


def _build_optimize_pairs(config):
    """Assemble the &OPTIMIZE section as (header, keyword pairs).

    Writes the optimization parameters from the flat agent config.

    Parameters
    ----------
    config : dict
        Agent JSON config.

    Returns
    -------
    tuple
        (header, pairs): section name and list of (key, value).
    """
    pairs = []

    opt_method = config.get('opt_method', '')
    if opt_method:
        pairs.append(('method', opt_method))

    opt_keys = [
        ('opt_maxit', 'maxit'),
        ('opt_energy', 'opt_energy'),
        ('opt_grms', 'opt_grms'),
        ('opt_gmax', 'opt_gmax'),
        ('opt_drms', 'opt_drms'),
        ('opt_dmax', 'opt_dmax'),
    ]
    for config_key, label in opt_keys:
        value = config.get(config_key)
        if value is not None:
            pairs.append((label, value))

    # The cell half of `optimize_cell` (#363, #364): the four thresholds the box is
    # judged on, the pressure its objective carries, and which lattice components
    # that pressure may move. Written only when they say something other than the
    # schema default, for the same reason the box switch is: a line that restates
    # what the run would apply anyway is noise between the reader and the file,
    # while a line that is missing is a different calculation between the two
    # carriers of one case.
    from pyrai3md.schema.config import DEFAULT
    for config_key in ('opt_csrms', 'opt_csmax', 'opt_cerms', 'opt_cemax',
                       'opt_pressure', 'opt_cell_coupling'):
        value = config.get(config_key)
        if value is None or value == DEFAULT[config_key]:
            continue
        pairs.append((config_key, value))

    # The step bound, written whenever the input named one. It has no default to
    # stay quiet about: `None` is the schema's way of saying "the search's own
    # radius", so any value at all is information, and a carrier that drops it
    # runs a different step size than the one the case declared - which is the
    # difference between a pressurised box landing inside its bar band and
    # overshooting it by eight times (round `tmp_20261019_122659`).
    trust_radius = config.get('opt_trust_radius')
    if trust_radius is not None:
        pairs.append(('opt_trust_radius', trust_radius))

    # The step model. `schema/adapter.OPTIMIZE_TYPES` has carried
    # `opt_use_rfo: 'b'` forever, so the classic reader accepted a line that no
    # writer ever produced: an example asking for RFO ran BFGS in `.input` mode
    # and RFO in yaml mode, one case name over two different searches. Written
    # only when set, because the schema default is False and a restated default
    # is noise between the reader and the file - the same rule as `optimize_cell`
    # just below.
    if config.get('opt_use_rfo'):
        pairs.append(('opt_use_rfo', True))

    # The box switch keeps its own name here, as it does everywhere else
    # (OPTIMIZE_PASSTHROUGH_KEYS): a classic input that omitted it would make
    # the text carrier relax a molecule while the YAML carrier relaxed a box,
    # and the two would report different runs under one case name. It is
    # written only when set, because the schema default is False and a line
    # printing a value the run would apply anyway is noise between the reader
    # and the file.
    if config.get('optimize_cell'):
        pairs.append(('optimize_cell', True))

    # Which electronic state the run drives. The classic spelling is the
    # unprefixed short name the case files use; the runtime flattener adds the
    # `opt_` prefix on its way into the schema, so `state_i` and `opt_state_i`
    # both land in `Optimize.opt_state_i` (SECTION_TYPES['optimize']). Written
    # only when it selects something other than the default: 0 is what the
    # schema applies anyway, and printing a default is noise between the file
    # and the reader. Omitting the line is what made the two carriers of
    # `examples/optimize_tda.yaml` different runs under one case name: round
    # tmp_20261015_211219 has the YAML leg on S1 (-77.17527079585400 Ha, the
    # backend printing `TDA gradients for state 1`) and the classic leg on the
    # ground state (-77.47568494347603 Ha, `RKS gradients`), 20 steps against
    # 12, and both judged PASS.
    # A per-center pair is written as the classic carrier's own list spelling -
    # the values separated by spaces - because the reader splits a value on
    # whitespace and a Python list would arrive as the literal "[0, 0]" that no
    # type code can parse (#460).
    def _classic_list(value):
        if isinstance(value, (list, tuple)):
            return ' '.join(str(int(item)) for item in value)
        return value

    state_i = config.get('opt_state_i')
    if state_i:
        pairs.append(('state_i', _classic_list(state_i)))
    state_j = config.get('opt_state_j')
    if state_j is not None:
        pairs.append(('state_j', _classic_list(state_j)))

    # The path family (`optimize.method` mep / irc / neb). Each keyword is
    # written in the section's own bare spelling - `path_radius` becomes
    # `opt_path_radius` on the way into the schema, the rule `state_i` above
    # follows - and only when it says something other than the default. One
    # carrier dropping one of these is one case name over two different paths:
    # the `.input` leg of `examples/path_neb.yaml` would otherwise build a
    # different chain than its yaml leg, and `path_irc.yaml` would walk a
    # different number of points.
    for config_key in ('opt_path_constraint', 'opt_path_radius',
                       'opt_path_inner_maxit', 'opt_path_inner_tol',
                       'opt_irc_direction', 'opt_irc_mode',
                       'opt_irc_mode_file', 'opt_neb_reactant',
                       'opt_neb_product', 'opt_neb_ts', 'opt_neb_images',
                       'opt_neb_interpolate', 'opt_neb_geodesic_threshold',
                       'opt_neb_geodesic_scaler',
                       'opt_neb_geodesic_min_neighbors', 'opt_neb_spring',
                       'opt_neb_climb', 'opt_neb_climb_threshold',
                       'opt_neb_step'):
        value = config.get(config_key)
        if value is None or value == DEFAULT[config_key]:
            continue
        pairs.append((config_key.split('opt_', 1)[1], value))

    return 'optimize', pairs


def _render_optimize_section(header, pairs):
    """Render the OPTIMIZE pairs as classic input text.

    Floats keep the legacy %.6e representation.

    Parameters
    ----------
    header : str
        Section name ('optimize').
    pairs : list of tuple
        (key, value) pairs from _build_optimize_pairs.

    Returns
    -------
    str
        Formatted &OPTIMIZE section text.
    """
    lines = ['&OPTIMIZE']
    for key, value in pairs:
        # The column is 14 wide because every legacy keyword fits in 13; a keyword
        # longer than that gets one space of its own rather than running into its
        # value, which is what made `opt_cell_coupling isotropic` read back as one
        # token and vanish.
        width = max(14, len(key) + 1)
        if isinstance(value, float):
            lines.append(f'{key:<{width}s}{value:.6e}')
        else:
            lines.append(f'{key:<{width}s}{value}')
    return '\n'.join(lines)


