def _build_control_pairs(config, task_name, skill_name='molcas_skill'):
    """Assemble the CONTROL section as (header, keyword pairs).

    The pairs are the single source for both the classic input text
    rendering and the pyrai3md config serialization.

    Parameters
    ----------
    config : dict
        Agent JSON config.
    task_name : str
        Task name used as the title.
    skill_name : str
        Skill identifier (e.g. 'molcas_skill'). Determines the theory method.

    Returns
    -------
    tuple
        (header, pairs): section name and list of (key, value).
    """
    title = task_name
    jobtype = _resolve_jobtype(config)
    # Prefer explicit theory (example configs); fall back to skill name
    theory = _join_tokens(config.get('theory', ''))
    if not theory:
        theory = skill_name.replace('_skill', '')  # molcas_skill -> molcas

    pairs = [
        ('title', title),
        ('jobtype', jobtype),
        ('theory', theory),
    ]

    reference = _join_tokens(config.get('reference', ''))
    if reference:
        pairs.append(('reference', reference))

    # Write the execution driver when non-default
    driver = config.get('driver', '')
    if driver and driver != 'main':
        pairs.append(('driver', driver))

    # Composite selector (qmmm / oniom). The classic input has no other
    # way to say that two theory methods are an additive QM/MM run.
    multiscale = str(config.get('multiscale_type', '') or '').strip()
    if multiscale:
        pairs.append(('multiscale_type', multiscale))

    # Write the test switch when asked for. Without this pair the classic
    # '.input' mode silently runs the framework default, so a qualification
    # round would judge the interrupted behaviour while the yaml mode
    # produced it -- the same class of gap _MD_ECHO_KEYS documents for the
    # MD section.
    if config.get('debug'):
        pairs.append(('debug', True))

    # Write the reproducibility seed when the source declared one. Same
    # class as the 'debug' pair above and the _MD_ECHO_KEYS table: the
    # dynamics draw is seeded from control.gl_seed, so a declaration the
    # classic text drops would make the two entry points draw different
    # initial velocities while both reported a pass.
    if 'gl_seed' in config:
        pairs.append(('gl_seed', int(config['gl_seed'])))

    # Write optimization method when non-default
    opt_method = config.get('opt_method', '')
    if opt_method and opt_method not in ('minima', ''):
        pairs.append(('optimization', opt_method))

    return 'control', pairs


def _render_section(header, pairs, separator=' '):
    """Render a sectioned dict fragment as classic input text.

    Parameters
    ----------
    header : str
        Section name without '&' (e.g. 'control').
    pairs : list of tuple
        (key, value) keyword pairs.
    separator : str, optional
        Column separator after the 14-char key column. The MD
        section historically uses no separator.

    Returns
    -------
    str
        Formatted '&HEADER' section text.
    """
    lines = ['&' + header.upper()]
    for key, value in pairs:
        pad = f'{key:<14}'
        if not separator and len(pad) == len(key):
            # Keys at or beyond the 14-char column would glue to the
            # value in the no-separator sections; the classic parser
            # tokenizes on whitespace, so a separating space is
            # mandatory there.
            pad += ' '
        lines.append(f'{pad}{separator}'
                     f'{_format_section_value(value)}')
    return '\n'.join(lines)





def _format_section_value(value):
    """Format a config value as a classic input keyword value.

    Booleans are lowercased (matching the xms handling); flat lists
    are joined into space-separated tokens; floats use the %.6e
    representation only when emitted by the optimize builder (plain
    values keep their str() form).

    Parameters
    ----------
    value : int, float, str, bool, or list
        Config value.

    Returns
    -------
    str
        Formatted value string.
    """
    if isinstance(value, bool):
        return str(value).lower()
    if isinstance(value, (list, tuple)):
        return ' '.join(str(v) for v in value)
    return str(value).strip()


def _collapse_shell_line(value):
    """Collapse shell commands into one ';'-separated line.

    Classic input keywords are single-line, but the config shell may
    be a yaml list or a newline-joined string. The commands are
    joined with '; ', which every normalization point (kernel
    get_shell, skill _normalize_shell) splits back equivalently,
    matching the '&environment shell:' single-line contract.

    Parameters
    ----------
    value : list or str
        Shell commands in any accepted form.

    Returns
    -------
    str
        One command line with '; ' separators; '' when empty.
    """
    fragments = value if isinstance(value, (list, tuple)) else [value]
    commands = []
    for fragment in fragments:
        if fragment is None:
            continue
        for line in str(fragment).splitlines():
            for piece in line.split(';'):
                piece = piece.strip()
                if piece:
                    commands.append(piece)
    return '; '.join(commands)


# Skill execution policy keys forwarded into the classic input skill
# section (&MOLCAS/&BAGEL/&PYSCF/&ORCA/&XTB/...). They belong to the
# skill schema Environment fields and reach the skill config through
# the skill section merge path. The framework &ENVIRONMENT section is
# not a carrier of any of them: it serves the framework dispatch layer
# only, and writing execution_mode there is refused outright (#300).
_EXECUTION_KEYS = (
    'execution_mode', 'keep_tmp',
    'slurm_time', 'slurm_partition', 'slurm_ntasks',
    'slurm_memory', 'slurm_command',
)


def _append_execution_keys(pairs, config, fallback=None):
    """Append execution_mode/slurm_* keys to a skill section.

    Only non-empty values are written so local-mode inputs stay
    minimal and the skill schema defaults apply otherwise.

    For a multi-theory composite the execution policy is per skill and
    rides in that skill's own ``section_params`` (``config`` here), so
    the shared top-level config is only a ``fallback`` for keys the
    per-skill section does not carry. For a single-skill job
    ``section_params`` is the flat config itself and ``fallback`` is
    the same dict, so the behavior is unchanged.

    Parameters
    ----------
    pairs : list of tuple
        Skill section (key, value) pairs to extend in place.
    config : dict
        This skill's parameter dict (per-skill section or flat config).
    fallback : dict, optional
        Shared top-level config consulted when ``config`` lacks a key.
    """
    for key in _EXECUTION_KEYS:
        value = config.get(key)
        if (value is None or value == '') and fallback is not None:
            value = fallback.get(key)
        if value is None or value == '':
            continue
        pairs.append((key, value))


def _append_periodic_pairs(config, pairs):
    """Emit the periodicity declaration of a &MOLECULE section.

    Shared by both carriers of the section: the multi-centre branch used to
    `return` before this code (it lives in the single-centre path), so a
    multi-centre example lost `pbc` and `cell` on its way into the classic
    input -- measured in round tmp_20261011_184226, where
    `multicenter_pbc_nve`'s `.input` carrier resolved to `pbc [0, 0, 0]` and
    the 99 A unset cell against the yaml carrier's `[1, 1, 1]` and 8.399091
    box, and the centre SCF then failed because it was run as an isolated,
    non-periodic cluster.
    """
    system_section = config.get('system', {})
    if not isinstance(system_section, dict):
        system_section = {}

    # Periodic boundary flags: emitted only when at least one direction
    # is on, so non-periodic configs stay byte-identical.
    pbc = config.get('pbc', system_section.get('pbc'))
    if isinstance(pbc, (list, tuple)) and pbc and any(int(v) for v in pbc):
        pairs.append(('pbc', [int(v) for v in pbc]))

    # Periodic cell: flatten the 3x3 lattice vectors into the
    # classic 'cell' keyword (9 floats, row-major); the schema
    # normalize step rebuilds lattice_vector from it in both input
    # modes, so periodic test YAMLs reach the skill System submodel.
    lattice_vector = config.get('lattice_vector',
                                system_section.get('lattice_vector'))
    if (isinstance(lattice_vector, (list, tuple))
            and len(lattice_vector) == 3
            and all(isinstance(row, (list, tuple)) and len(row) == 3
                    for row in lattice_vector)
            and any(abs(v) > 0
                    for row in lattice_vector for v in row)):
        pairs.append(('cell',
                      [float(v) for row in lattice_vector for v in row]))
    else:
        # Six-parameter cell ([a, b, c, alpha, beta, gamma], lengths
        # Angstrom): emitted when it differs from the unset sentinel so
        # a YAML-defined periodic box survives into the classic input
        # and the agent config; the runtime normalize step derives
        # lattice_vector from it in both modes.
        from ...schema.config import DEFAULT
        cell = config.get('cell', system_section.get('cell'))
        if (isinstance(cell, (list, tuple)) and len(cell) in (6, 9)
                and [float(v) for v in cell] != list(DEFAULT['cell'])):
            pairs.append(('cell', [float(v) for v in cell]))


def _append_framework_embedding_pairs(config, pairs):
    """Emit the framework's embedding / read_charge as the bools they are.

    `system.embedding` and `system.read_charge` are bool fields
    (`schema/config.py:1125-1126`) since the QMMM wiring took over the field
    vocabulary: the strings `charge` / `potential` and a charge file name
    belong to the skill's own config section, and rendering them into
    &MOLECULE fails `PyRAIConfig` with a bool_parsing error on both framework
    carriers. A truthy skill value therefore becomes the framework switch that
    asks for the same thing - embed, and take the background charges from
    '{title}.charge' - while an absent or false value emits nothing, keeping a
    non-ESPF config byte-identical.
    """
    for key in ('embedding', 'read_charge'):
        value = config.get(key)
        if isinstance(value, str):
            text = value.strip().lower()
            value = bool(text) and text not in ('none', 'false', '0')
        if value:
            pairs.append((key, bool(value)))


def _build_molecule_pairs(config):
    """Assemble the MOLECULE section as (header, keyword pairs).

    The pyrai3md config carries the canonical skill state vocabulary
    (nstate/state_spin/charges/multiplicity/...) so the agent
    pipeline consumes it through the same merge sources as classic
    input; the classic text rendering derives the legacy ci/spin
    keywords from the same values at render time.

    Parameters
    ----------
    config : dict
        Agent JSON config.

    Returns
    -------
    tuple
        (header, pairs): section name and list of (key, value).
    """
    pairs = []

    # Multi-center: the center-dimensioned keywords (highlevel/ci/spin/
    # coupling) are emitted verbatim as classic ';'-separated strings
    # and the single-center nstate/state_spin/current_state derivation
    # is skipped (per-center nstate is derived from ci downstream).
    if _is_multicenter(config):
        charges = config.get('charges')
        if charges is not None:
            pairs.append(('charges', _render_center_string(charges)))
        multiplicity = config.get('multiplicity')
        if multiplicity is not None:
            pairs.append(('multiplicity',
                          _render_center_string(multiplicity)))
        for key in ('highlevel', 'midlevel', 'highref', 'midref',
                    'ci', 'spin', 'coupling'):
            value = config.get(key)
            if value is None or value == '' or value == []:
                continue
            pairs.append((key, _render_center_string(value)))
        # ONIOM electrostatic embedding keywords ride with the region
        # keywords, as the framework bools they are (see
        # _append_framework_embedding_pairs).
        _append_framework_embedding_pairs(config, pairs)
        _append_charge_iteration_pairs(config, pairs)
        _append_periodic_pairs(config, pairs)
        return 'molecule', pairs

    nstate = config.get('nstate')
    if nstate is not None:
        pairs.append(('nstate', nstate))
    state_spin = config.get('state_spin')
    if state_spin:
        pairs.append(('state_spin', list(state_spin)))
    charges = config.get('charges')
    if charges is not None:
        pairs.append(('charges', charges))
    multiplicity = config.get('multiplicity')
    if multiplicity is not None:
        pairs.append(('multiplicity', multiplicity))

    # Explicit ci/spin (classic string '3'/'0' or typed list [3]/[0])
    # win over the nstate/state_spin derivation so a single-center
    # multistate example renders the same electronic structure in the
    # classic input and the agent config as in the direct-YAML mode.
    ci = config.get('ci')
    if ci is not None and ci != '' and ci != []:
        pairs.append(('ci', ci))
    spin = config.get('spin')
    if spin is not None and spin != '' and spin != []:
        pairs.append(('spin', spin))

    # Initial MD state (0-based): the test YAML carries it in the
    # system submodel (dev_tool), legacy configs may keep it flat.
    system_section = config.get('system', {})
    if not isinstance(system_section, dict):
        system_section = {}
    current_state = config.get('current_state',
                               system_section.get('current_state'))
    if current_state is not None:
        pairs.append(('current_state', current_state))

    _append_periodic_pairs(config, pairs)

    # Transition pairs (coupling): a classic string ('1 2, 2 3') is
    # already external 1-based and emitted verbatim; a typed list is
    # stored 0-based and the classic text renderer shifts it to
    # 1-based state indices at render time.
    coupling = config.get('coupling', [])
    if isinstance(coupling, str):
        if coupling.strip():
            pairs.append(('coupling', coupling.strip()))
    elif coupling:
        pairs.append(('coupling', [list(pair) for pair in coupling]))

    # Single-center ONIOM region: the flat 1-based lists the source
    # declares. Without them the classic carrier loses the partition and
    # the queue falls back to a whole-system run.
    for key in ('highlevel', 'midlevel', 'highref', 'midref'):
        value = config.get(key)
        if value is None or value == '' or value == []:
            continue
        # Single center: a flat 1-based list, space-joined. The ';'
        # center string belongs to the multi-center branch only.
        pairs.append((key, _format_section_value(value)))

    # QMMM's QM 0-order charges: a single-center flat list in
    # highlevel order. Without the echo the classic carrier has no
    # q_qm and the energy task refuses the run.
    q_qm = config.get('q_qm')
    if q_qm:
        pairs.append(('q_qm', _format_section_value(q_qm)))

    # Single-center ONIOM region + electrostatic embedding keywords:
    # highlevel/midlevel are flat lists in their external (1-based) form
    # (the renderer space-joins them). The embedding switches ride with them
    # as framework bools (see _append_framework_embedding_pairs), and they
    # appear together because a charge embedding needs a region in the ONIOM
    # model. Absent/false keywords emit nothing, keeping a non-ESPF config
    # byte-identical.
    _append_framework_embedding_pairs(config, pairs)

    # QMMM charge iteration: the switch plus its two numbers.
    _append_charge_iteration_pairs(config, pairs)

    return 'molecule', pairs


def _append_charge_iteration_pairs(config, pairs):
    """Emit the charge-iteration keywords, and only when asked for.

    Absent/false keywords emit nothing, so every carrier that does not
    iterate stays byte-identical; a classic carrier that lost `sc_charge`
    would silently run the fixed-round scheme the YAML did not ask for.
    """
    if config.get('sc_charge'):
        pairs.append(('sc_charge', True))
        for key in ('sc_charge_maxiter', 'sc_charge_threshold'):
            value = config.get(key)
            if value not in (None, ''):
                pairs.append((key, value))


def _render_molecule_section(header, pairs, separator=' '):
    """Render the MOLECULE pairs as classic input text.

    Derives the legacy ci/spin keywords from nstate/state_spin/
    multiplicity:
    - 'state_spin' (list of 2S per state) is the primary source.
      It is grouped by spin value to produce:
        ci   = number of states per spin multiplicity
        spin = total spin S per multiplicity (S = 2S/2)
      Example: state_spin=[0,0,2,2] -> ci='2 2', spin='0 1'
    - Fallback: when state_spin is absent, uses nstate and
      multiplicity to produce a single-spin entry.

    Classic input semantics:
        ci   : number of states for each spin multiplicity
        spin : total spin quantum number S (0=singlet, 1=triplet)
        nstate = sum(ci)

    Parameters
    ----------
    header : str
        Section name ('molecule').
    pairs : list of tuple
        (key, value) pairs from _build_molecule_pairs.

    Returns
    -------
    str
        Formatted &MOLECULE section text.
    """
    values = dict(pairs)

    # Multi-center: the center keywords already carry classic ';'-
    # separated strings (highlevel/ci/spin/coupling); emit every pair
    # verbatim and skip the single-center ci/spin derivation and the
    # coupling 0->1 shift (the strings are already external 1-based).
    if ('highlevel' in values or 'midlevel' in values
            or (isinstance(values.get('ci'), str)
                and ';' in values.get('ci', ''))):
        lines = ['&MOLECULE']
        for key, value in pairs:
            pad = f'{key:<14}'
            if not separator and len(pad) == len(key):
                # Same rule as _render_section: a keyword longer than the
                # 14-char column must still be separated from its value,
                # because the classic parser tokenizes on whitespace.
                pad += ' '
            lines.append(f'{pad}{separator}'
                         f'{_format_section_value(value)}')
        return '\n'.join(lines)

    nstate = values.get('nstate', 1)
    state_spin = values.get('state_spin', [])
    multiplicity = values.get('multiplicity', 1)

    # CI settings: an explicit ci/spin pair (classic string or typed
    # list) wins; otherwise derive from ci_roots/ci_spin, state_spin,
    # or nstate + multiplicity (config ci_roots/ci_spin -> input
    # ci/spin).
    ci_roots = values.get('ci_roots', [])
    ci_spin = values.get('ci_spin', [])
    explicit_ci = values.get('ci')
    explicit_spin = values.get('spin')
    if explicit_ci is not None:
        ci_str = (explicit_ci if isinstance(explicit_ci, str)
                  else ' '.join(str(c) for c in explicit_ci))
        if explicit_spin is not None:
            spin_str = (explicit_spin if isinstance(explicit_spin, str)
                        else ' '.join(str(s) for s in explicit_spin))
        else:
            spin_str = str((multiplicity - 1) // 2)
    elif ci_roots:
        ci_str = ' '.join(str(c) for c in ci_roots)
        spin_str = ' '.join(str(s) for s in ci_spin)
    elif state_spin:
        # One block per multiplicity in ascending 2S order, the order
        # the molcas skill's own normalize puts the ladder in
        # (SOC [0,0,2] -> '2 1' / '0 1'; [0,2,0] -> '2 1' / '0 1').
        ci_roots, spins = _group_state_spin(state_spin)
        ci_str = ' '.join(str(c) for c in ci_roots)
        spin_str = ' '.join(str(s // 2) for s in spins)
    else:
        spin_s = (multiplicity - 1) // 2
        ci_str = str(nstate)
        spin_str = str(spin_s)

    lines = [
        '&MOLECULE',
        f'ci            {ci_str}',
        f'spin          {spin_str}',
    ]

    for key, value in pairs:
        if key in ('nstate', 'state_spin', 'charges', 'multiplicity',
                   'ci', 'spin'):
            continue  # Consumed via ci/spin above in classic input
        if key == 'coupling':
            if isinstance(value, str):
                # Classic string form: already external 1-based.
                lines.append(f'coupling      {value}')
                continue
            rendered = ', '.join(
                f'{pair[0] + 1} {pair[1] + 1}'
                for pair in value
                if isinstance(pair, (list, tuple)) and len(pair) >= 2)
            if rendered:
                lines.append(f'coupling      {rendered}')
            continue
        if key == 'current_state':
            lines.append(f'current_state   {value}')
            continue
        lines.append(f'{key:<14}{separator}{_format_section_value(value)}')

    return '\n'.join(lines)


