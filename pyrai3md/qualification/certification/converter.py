def _build_md_pairs(config):
    """Assemble the &MD section as (header, keyword pairs).

    root is the dynamics initial state in its external 1-based
    spelling (an explicit config value passes through verbatim; the
    current_state derivation emits current_state + 1); activestate is
    passed through from the config (defaults to 1). Dynamics and
    ensemble keywords deviating from the framework defaults are echoed via
    _append_md_echo_pairs so the classic input and the agent config
    run the same dynamics as the direct-YAML mode.

    Parameters
    ----------
    config : dict
        Agent JSON config.

    Returns
    -------
    tuple
        (header, pairs): section name and list of (key, value).
    """
    system_section = config.get('system', {})
    if not isinstance(system_section, dict):
        system_section = {}

    # Multi-center: root is a per-center list/string emitted verbatim as
    # a classic ';'-separated string. activestate is written only when
    # the config carries it, so the framework default (0: all-state
    # gradients) applies otherwise and matches the direct-YAML mode.
    if _is_multicenter(config):
        root_value = config.get('root', system_section.get('root'))
        if root_value is not None:
            pairs = [('root', _render_center_string(root_value))]
            activestate = config.get('activestate')
            if activestate is not None:
                pairs.append(('activestate', activestate))
            return 'md', _append_md_echo_pairs(config, pairs)

    # Single center: an explicit md.root keeps its external 1-based
    # spelling verbatim; the current_state derivation converts the
    # internal 0-based value to the same external spelling (root is
    # 1-based in every artifact, matching the adapter contract).
    current_state = config.get('current_state',
                               system_section.get('current_state'))
    root = config.get('root', system_section.get('root'))
    try:
        root = int(root) if root is not None else None
    except (TypeError, ValueError):
        root = None
    if root is None:
        root = (current_state + 1) if current_state is not None else 1
    activestate = config.get('activestate', 1)

    pairs = [
        ('root', root),
        ('activestate', activestate),
    ]

    return 'md', _append_md_echo_pairs(config, pairs)


